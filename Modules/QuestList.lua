local function AddGiverPins(map, mapID, mapName)
	local level = Plain(UnitLevel("player")) or 60
	local groups, order = {}, {}
	local function Consider(row, x, y, who, state)
		local key = string.format("%s|%.3f|%.3f", who, x, y)
		local group = groups[key]
		if not group then
			group = { giver = who, x = x, y = y, quests = {}, state = "done", tracked = false }
			groups[key] = group
			order[#order + 1] = group
		end
		group.quests[#group.quests + 1] = { row = row, state = state }
		if STATE_RANK[state] > STATE_RANK[group.state] then
			group.state = state
		end
		if trackedQuestID == row[F_ID] then
			group.tracked = true
		end
	end
	local seen = {}
	-- A quest ready to hand in is pinned at its turn-in, everything else at its giver.
	local function Place(row, endOnly)
		if seen[row] or not Eligible(row) then
			return
		end
		local state = QuestState(row, level)
		local x, y, who
		if state == "ready" and resolvedEnd[row] then
			x, y = ProjectOnMap(resolvedEnd[row], mapID)
			who = row[F_ENDER]
		elseif not endOnly and resolved[row] then
			x, y = ProjectOnMap(resolved[row], mapID)
			who = row[F_GIVER]
		end
		if x then
			seen[row] = true
			Consider(row, x, y, who, state)
		end
	end
	-- Rows the client placed on this map or on a city inside it.
	local maps = { mapID }
	local okC, children = pcall(C_Map.GetMapChildrenInfo, mapID)
	if okC and type(children) == "table" then
		for _, child in ipairs(children) do
			if Plain(child.mapID) then
				maps[#maps + 1] = child.mapID
			end
		end
	end
	for _, id in ipairs(maps) do
		for _, row in ipairs(rowsByMap and rowsByMap[id] or {}) do
			Place(row, false)
		end
		for _, row in ipairs(endRowsByMap and endRowsByMap[id] or {}) do
			Place(row, true)
		end
	end
	-- Givers with a map percentage only (collected in game on this zone).
	local areaID = zoneByName[mapName:lower()]
	for _, row in ipairs(areaID and byZone[areaID] or {}) do
		if not seen[row] and not (resolved and resolved[row]) and (row[F_X] ~= 0 or row[F_Y] ~= 0) and Eligible(row) then
			seen[row] = true
			Consider(row, row[F_X] / 100, row[F_Y] / 100, row[F_GIVER], QuestState(row, level))
		end
	end
	for _, group in ipairs(order) do
		if group.state ~= "done" or M.db.pinCompleted or group.tracked then
			table.sort(group.quests, function(a, b) return ByLevel(a.row, b.row) end)
			map:AcquirePin(PIN_TEMPLATE, "giver", group)
		end
	end
end

local function AddZoneBadges(map, continentMapID)
	local ok, children = pcall(C_Map.GetMapChildrenInfo, continentMapID, MAP_ZONE, false)
	if not ok or type(children) ~= "table" then
		return
	end
	local level = Plain(UnitLevel("player")) or 60
	for _, child in ipairs(children) do
		local name = Plain(child.name)
		local areaID = name and zoneByName[name:lower()]
		local rows = areaID and byZone[areaID]
		if rows then
			local done, total, available, inLog, lo, hi = 0, 0, 0, 0, 0, 0
			for _, row in ipairs(rows) do
				if Eligible(row) then
					total = total + 1
					local state = QuestState(row, level)
					if state == "done" then
						done = done + 1
					elseif state == "available" then
						available = available + 1
					elseif state == "ready" or state == "progress" then
						inLog = inLog + 1
					end
					local lv = row[F_LEVEL]
					if lv > 0 then
						if lo == 0 or lv < lo then lo = lv end
						if lv > hi then hi = lv end
					end
				end
			end
			local okR, minX, maxX, minY, maxY = pcall(C_Map.GetMapRectOnMap, child.mapID, continentMapID)
			if total > 0 and okR and Plain(minX) and Plain(maxX) and Plain(minY) and Plain(maxY) then
				map:AcquirePin(PIN_TEMPLATE, "badge", {
					mapID = child.mapID, name = name, done = done, total = total, available = available, inLog = inLog,
					lo = lo, hi = hi, x = (minX + maxX) / 2, y = (minY + maxY) / 2,
				})
			end
		end
	end
end


