local function HeaderClick(self)
	if self.entry and self.entry.header then
		collapsed[self.entry.key] = not collapsed[self.entry.key] or nil
		PlaySound(collapsed[self.entry.key] and SOUNDKIT.IG_MAINMENU_OPTION_CHECKBOX_OFF or SOUNDKIT.IG_MAINMENU_OPTION_CHECKBOX_ON)
		Panel:Update()
	end
