local lastInstance = nil

local function DungeonSummary()
	if not (M.isEnabled and M.db.dungeonSummary and QL.byZone) then
		return
	end
	local okI, inInstance, kind = pcall(IsInInstance)
	if not okI or not inInstance or (kind ~= "party" and kind ~= "raid") then
		lastInstance = nil
		return
	end
	local okN, name = pcall(GetInstanceInfo)
	name = okN and QL.Plain(name) or nil
	if not name or name == lastInstance then
		return
	end
	lastInstance = name
	local data = QL.Data()
	local dungeonID
	for id, dname in pairs(data.dungeons or {}) do
		if dname:lower() == name:lower() then
			dungeonID = id
		end
	end
	if not dungeonID then
		return
	end
	local missing, inLog, done, total = {}, 0, 0, 0
	for _, row in ipairs(data.quests or {}) do
		if row[QL.F_DUNGEON] == dungeonID and QL.Eligible(row) then
			total = total + 1
			if QL.IsCompleted(row[QL.F_ID]) then
				done = done + 1
			elseif QL.IsOnQuest(row[QL.F_ID]) then
				inLog = inLog + 1
			else
				missing[#missing + 1] = row
			end
		end
	end
	if total == 0 then
		return
	end
	MelloUI:Print("%s: %d of %d quests done, %d in your log, %d not picked up.", name, done, total, inLog, #missing)
	for _, row in ipairs(data.quests or {}) do
		if row[QL.F_DUNGEON] == dungeonID and QL.Eligible(row) and QL.IsOnQuest(row[QL.F_ID]) and QL.IsReadyForTurnIn(row[QL.F_ID]) and (row[QL.F_ENDER] or "") ~= "" then
			local endZone = QL.EnderZoneName(row) or QL.Data().zones[QL.ZoneOf(row)]
			print(string.format("   |cffffd200%s|r is ready: turn in to %s%s", row[QL.F_TITLE], row[QL.F_ENDER], endZone and (" in " .. endZone) or ""))
		end
	end
	table.sort(missing, QL.ByLevel)
	for i, row in ipairs(missing) do
		if i > 12 then
			print(string.format("   ... and %d more; see the Dungeons tab of the quest list.", #missing - 12))
			break
		end
		local r, g, b = QL.DifficultyColor(row[QL.F_LEVEL])
		local zone = data.zones[row[QL.F_GIVERZONE]] or data.zones[row[QL.F_ZONE]]
		local from = row[QL.F_GIVER] ~= "" and row[QL.F_GIVER] or "giver unknown"
		print(string.format("   |cff%02x%02x%02x%s|r (%d)  -  %s%s", r * 255, g * 255, b * 255, row[QL.F_TITLE], row[QL.F_LEVEL],
			from, zone and (", " .. zone) or ""))
	end
end

