local function DungeonIDByName(name)
	if not name then
		return 0
	end
	for id, dname in pairs(Data().dungeons or {}) do
		if dname:lower() == name:lower() then
			return id
		end
	end
	return 0
end

-- Done / total of a dungeon's quests for this character.
local function DungeonProgress(dungeonID)
	local done, total = 0, 0
	for _, row in ipairs(byDungeon and byDungeon[dungeonID] or {}) do
		if Eligible(row) then
			total = total + 1
			if IsCompleted(row[F_ID]) then
				done = done + 1
			end
		end
	end
	return done, total
end

local function QuestState(row, level)
	if IsCompleted(row[F_ID]) then
		return "done"
	end
	if IsOnQuest(row[F_ID]) then
		return IsReadyForTurnIn(row[F_ID]) and "ready" or "progress"
	end
	return row[F_REQ] <= level and "available" or "locked"
end

