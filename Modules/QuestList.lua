	local data = self.data
	if not data or button ~= "LeftButton" then
		return
	end
	if self.kind == "giver" then
		if data.tracked then
			ClearWaypoint()
			PlaySound(SOUNDKIT.UI_MAP_WAYPOINT_REMOVE or SOUNDKIT.IG_MAINMENU_OPTION_CHECKBOX_OFF)
