local mapIDByName = nil

local function MapIDForZoneName(name)
	if not mapIDByName then
		mapIDByName = {}
		local ok, root = pcall(C_Map.GetFallbackWorldMapID)
		root = ok and Plain(root) or 947
		local okC, children = pcall(C_Map.GetMapChildrenInfo, root, nil, true)
		if okC and type(children) == "table" then
			for _, info in ipairs(children) do
				local n = Plain(info.name)
				if n and not mapIDByName[n:lower()] then
					mapIDByName[n:lower()] = info.mapID
				end
			end
		end
	end
	return mapIDByName[name:lower()]
end

local function ZoneNameForMap(mapID)
	if not mapID then
		return nil
	end
	local ok, info = pcall(C_Map.GetMapInfo, mapID)
	if ok and info then
		return Plain(info.name)
	end
	return nil
end

local function CurrentMapID()
	local ok, id = pcall(WorldMapFrame.GetMapID, WorldMapFrame)
	local mapID = ok and Plain(id) or nil
	if not mapID then
		local okP, pid = pcall(C_Map.GetBestMapForUnit, "player")
		mapID = okP and Plain(pid) or nil
	end
	return mapID
end

local function CurrentAreaID()
	local mapID = CurrentMapID()
	local name = ZoneNameForMap(mapID)
	if not name then
		return nil, nil
	end
	local areaID = zoneByName[name:lower()]
	if not areaID then
		-- A continent or the world is shown: use the zone the player is in.
		local okP, pid = pcall(C_Map.GetBestMapForUnit, "player")
		local pname = ZoneNameForMap(okP and Plain(pid) or nil)
		if pname then
			areaID, name = zoneByName[pname:lower()], pname
		end
	end
	return areaID, name
end

-- Continent (0 Eastern Kingdoms, 1 Kalimdor) of the map shown, walking up the map tree.
local function CurrentContinent()
	local mapID = CurrentMapID()
	for _ = 1, 6 do
		if not mapID then break end
		local ok, info = pcall(C_Map.GetMapInfo, mapID)
		if not ok or not info then break end
		local name = Plain(info.name)
		if name then
			for c, cname in pairs(Data().continentNames or {}) do
				if cname:lower() == name:lower() then
					return c, cname
				end
			end
		end
		mapID = Plain(info.parentMapID)
		if not mapID or mapID == 0 then break end
	end
	local areaID = CurrentAreaID()
	if areaID then
		local c = Data().zoneContinent and Data().zoneContinent[areaID]
		if c and c >= 0 then
			return c, Data().continentNames[c]
		end
	end
	return nil, nil
end

local function SetWaypoint(row, atEnder)
	local mapID, x, y
	if atEnder then
		mapID, x, y = EndPoint(row)
	end
	if not x then
		mapID, x, y = GiverPoint(row)
	end
	if not x then
		return false
	end
	if not mapID then
		local zoneName = Data().zones[ZoneOf(row)]
		mapID = zoneName and MapIDForZoneName(zoneName)
	end
	if not mapID or not C_Map.SetUserWaypoint or not UiMapPoint then
		return false
	end
	local okCan, can = pcall(C_Map.CanSetUserWaypointOnMap, mapID)
	if okCan and can == false then
		return false
	end
	-- Through the Route module when it is on: pin, route, label and notice in one.
	local R = MelloUI.Route
	if R and R.isEnabled and R.SetDestinationTo then
		local who = atEnder and (row[F_ENDER] or "") ~= "" and row[F_ENDER] or row[F_GIVER]
		local icon = atEnder and "|A:QuestTurnin:16:16|a " or "|A:QuestNormal:16:16|a "
		local label = icon .. row[F_TITLE] .. (who ~= "" and (" - " .. who) or "")
		local what = atEnder and "turn-in" or "quest giver"
		local text = string.format("%sTracking %s %s for %s, {dist} away", icon, what, who ~= "" and who or "", row[F_TITLE])
		if R:SetDestinationTo({ mapID = mapID, x = x, y = y }, label, true, text) then
			trackedQuestID = row[F_ID]
			return true
		end
	end
	local point = UiMapPoint.CreateFromCoordinates(mapID, x, y)
	local ok = pcall(C_Map.SetUserWaypoint, point)
	if ok and C_SuperTrack and C_SuperTrack.SetSuperTrackedUserWaypoint then
		pcall(C_SuperTrack.SetSuperTrackedUserWaypoint, true)
	end
	if ok then
		trackedQuestID = row[F_ID]
	end
	return ok
end

-- Route to a point on a map (entrance, dock, flight master): the Route
-- module when it is on, else a plain user waypoint.
local function RouteToPoint(mapID, x, y, label, notice)
	if not (mapID and x and y) then
		return false
	end
	local R = MelloUI.Route
	if R and R.isEnabled and R.SetDestinationTo then
		return R:SetDestinationTo({ mapID = mapID, x = x, y = y }, label, true, notice) and true or false
	end
	if not (C_Map.SetUserWaypoint and UiMapPoint) then
		return false
	end
	local okCan, can = pcall(C_Map.CanSetUserWaypointOnMap, mapID)
	if okCan and can == false then
		return false
	end
	local ok = pcall(C_Map.SetUserWaypoint, UiMapPoint.CreateFromCoordinates(mapID, x, y))
	if ok and C_SuperTrack and C_SuperTrack.SetSuperTrackedUserWaypoint then
		pcall(C_SuperTrack.SetSuperTrackedUserWaypoint, true)
	end
	return ok
end

local function ClearWaypoint()
	if C_Map.ClearUserWaypoint then
		pcall(C_Map.ClearUserWaypoint)
	end
	trackedQuestID = nil
end

-- The pin can be removed from the map itself; forget the quest then.
local function SyncTracked()
	if trackedQuestID and C_Map.HasUserWaypoint then
		local ok, has = pcall(C_Map.HasUserWaypoint)
		if ok and has == false then
			trackedQuestID = nil
		end
	end
end

