local function RowClick(self)
	if not (self.entry and self.entry.row) then
		return
	end
	if trackedQuestID == self.entry.row[F_ID] then
		ClearWaypoint()
		PlaySound(SOUNDKIT.UI_MAP_WAYPOINT_REMOVE or SOUNDKIT.IG_MAINMENU_OPTION_CHECKBOX_OFF)
	elseif SetWaypoint(self.entry.row, self.entry.ready) then
		PlaySound(SOUNDKIT.UI_MAP_WAYPOINT_CLICK_TO_PLACE or SOUNDKIT.IG_MAINMENU_OPTION_CHECKBOX_ON)
	end
	Panel:Update()
	if RefreshPins then
		RefreshPins()
	end
end

local function RowEnter(self)
	local e = self.entry
	if not e or not e.row then return end
	local row = e.row
	GameTooltip:SetOwner(self, "ANCHOR_LEFT")
	local r, g, b = DifficultyColor(row[F_LEVEL])
	GameTooltip:SetText(row[F_TITLE], r, g, b)
	GameTooltip:AddLine(string.format("Level %d, requires level %d", row[F_LEVEL], row[F_REQ]), 0.8, 0.8, 0.8)
	if row[F_DUNGEON] ~= 0 and Data().dungeons[row[F_DUNGEON]] then
		GameTooltip:AddLine("Dungeon quest: " .. Data().dungeons[row[F_DUNGEON]], 0.75, 0.61, 0)
	end
	if row[F_CHAIN] ~= 0 and Data().chains[row[F_CHAIN]] then
		local step, total, nextRow = ChainInfo(row)
		GameTooltip:AddLine(string.format("Step %d of %d in the chain: %s", step, total, Data().chains[row[F_CHAIN]]), 0.75, 0.61, 0)
		if nextRow then
			GameTooltip:AddLine("Next: " .. nextRow[F_TITLE], 0.6, 0.6, 0.6)
		end
	end
	if row[F_GIVER] ~= "" then
		local giverZone = Data().zones[ZoneOf(row)]
		GameTooltip:AddLine("From " .. row[F_GIVER] .. (giverZone and (" in " .. giverZone) or ""), 0.8, 0.8, 0.8)
	end
	if (row[F_ENDER] or "") ~= "" then
		if SameEnder(row) then
			GameTooltip:AddLine("Turn in to the same NPC", 0.6, 0.6, 0.6)
		else
			local endZone = EnderZoneName(row)
			GameTooltip:AddLine("Turn in to " .. row[F_ENDER] .. (endZone and (" in " .. endZone) or ""), 0.8, 0.8, 0.8)
