			end
		end
	elseif row[F_GIVER] ~= "" then
		where = row[F_GIVER]
		local _, gx, gy = GiverPoint(row)
		if gx then
			where = where .. string.format("   %.1f, %.1f", gx * 100, gy * 100)
		end
		if entry.showZone then
			local giverZone = Data().zones[ZoneOf(row)]
			if giverZone then
				where = giverZone .. "  -  " .. where
			end
		end
	else
		where = entry.showZone and (Data().zones[row[F_ZONE]] or "") or "quest giver unknown"
	end
	button.where:SetText(where)
	if entry.completed then
		button.where:SetTextColor(0.4, 0.4, 0.4)
	else
		button.where:SetTextColor(GOLD_DIM[1], GOLD_DIM[2], GOLD_DIM[3])
	end
