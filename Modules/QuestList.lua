function QL.ZoneOf(row)
	local override = zoneOverride and zoneOverride[row]
	if override then
		return override
	end
	return row[QL.F_GIVERZONE] ~= 0 and row[QL.F_GIVERZONE] or row[QL.F_ZONE]
end

--------------------------------------------------------------------------------
-- World positions
--
-- Vanilla data gives world coordinates. The client turns them into a
-- continent-map position; the continent map's hit test says which zone (and
-- city) is there, and the zone's rectangle on the continent gives the position
-- on the zone map. Build-time zone guesses are wrong at zone edges and on maps
-- Forever changed (Stormwind with its harbour), so this is done here.
--------------------------------------------------------------------------------

function QL.VectorXY(pos)
	if type(pos) ~= "table" then
		return nil, nil
	end
	local x, y = QL.Plain(pos.x), QL.Plain(pos.y)
	if (x == nil or y == nil) and type(pos.GetXY) == "function" then
		local ok, gx, gy = pcall(pos.GetXY, pos)
		if ok then
			x, y = QL.Plain(gx), QL.Plain(gy)
		end
	end
	return x, y
end

-- Is `mapID` the map `uiMapID` or one of its parents (city inside a zone)?
local function IsOnOrUnder(uiMapID, mapID)
	local id = uiMapID
	for _ = 1, 4 do
		if id == mapID then
			return true
		end
		local ok, info = pcall(C_Map.GetMapInfo, id)
		id = ok and type(info) == "table" and QL.Plain(info.parentMapID) or nil
		if not id or id == 0 then
			return false
		end
	end
	return false
end

local rectCache = {}

-- Rectangle of a map on its continent map, cached.
local function RectOn(mapID, contMapID)
	local key = mapID .. ":" .. contMapID
	local r = rectCache[key]
	if r == nil then
		local ok, minX, maxX, minY, maxY = pcall(C_Map.GetMapRectOnMap, mapID, contMapID)
		minX, maxX, minY, maxY = QL.Plain(minX), QL.Plain(maxX), QL.Plain(minY), QL.Plain(maxY)
		r = (ok and minX and maxX and minY and maxY and maxX > minX and maxY > minY) and { minX, maxX, minY, maxY } or false
		rectCache[key] = r
	end
	return r or nil
end

local function InRect(r, cx, cy)
	local x, y = (cx - r[1]) / (r[2] - r[1]), (cy - r[3]) / (r[4] - r[3])
	if x >= 0 and x <= 1 and y >= 0 and y <= 1 then
		return x, y
	end
	return nil
end

-- A world point as { mapID, x, y, cx, cy, contMapID }: the deepest map that
-- holds it (city before zone) and its position there, or nil.
function QL.ResolveWorld(cont, wx, wy)
	if not (C_Map.GetMapPosFromWorldPos and CreateVector2D and C_Map.GetMapInfoAtPosition and C_Map.GetMapRectOnMap) then
		return nil
	end
	local ok, contMapID, pos = pcall(C_Map.GetMapPosFromWorldPos, cont, CreateVector2D(wx, wy))
	contMapID = ok and QL.Plain(contMapID) or nil
	local cx, cy = QL.VectorXY(pos)
	if not (contMapID and cx and cy) then
		return nil
	end
	local okZ, zinfo = pcall(C_Map.GetMapInfoAtPosition, contMapID, cx, cy)
	local zone = okZ and type(zinfo) == "table" and QL.Plain(zinfo.mapID) or nil
	if not zone or zone == contMapID then
		return nil
	end
	local r = RectOn(zone, contMapID)
	local x, y
	if r then
		x, y = InRect(r, cx, cy)
	end
	if not x then
		return nil
	end
	-- One level deeper: a city inside the zone.
	local okC, cinfo = pcall(C_Map.GetMapInfoAtPosition, zone, x, y)
	local child = okC and type(cinfo) == "table" and QL.Plain(cinfo.mapID) or nil
	if child and child ~= zone then
		local r2 = RectOn(child, contMapID)
		local x2, y2
		if r2 then
			x2, y2 = InRect(r2, cx, cy)
		end
		if x2 then
			zone, x, y = child, x2, y2
		end
	end
	return { mapID = zone, x = x, y = y, cx = cx, cy = cy, contMapID = contMapID }
end

-- Position of a resolved point on the map shown (its own map, a parent, or a
-- child), or nil when the point is elsewhere.
function QL.ProjectOnMap(res, mapID)
	if res.mapID == mapID then
		return res.x, res.y
	end
	if not (IsOnOrUnder(res.mapID, mapID) or IsOnOrUnder(mapID, res.mapID)) then
		return nil
	end
	local r = RectOn(mapID, res.contMapID)
	if not r then
		return nil
	end
	return InRect(r, res.cx, res.cy)
end

-- Where a quest giver is: uiMapID, x, y (0..1) from the client's placement,
-- else the build-time zone and map percentage.
function QL.GiverPoint(row)
	local res = QL.resolved and QL.resolved[row]
	if res then
		return res.mapID, res.x, res.y
	end
	if row[QL.F_X] ~= 0 or row[QL.F_Y] ~= 0 then
		return nil, row[QL.F_X] / 100, row[QL.F_Y] / 100
	end
	return nil
end

-- Is the quest handed back to the NPC that gave it?
function QL.SameEnder(row)
	local ender, giver = row[QL.F_ENDER] or "", row[QL.F_GIVER] or ""
	if ender == "" then
		return true
	end
	local enpc, gnpc = row[QL.F_ENDERNPC] or 0, row[QL.F_NPC] or 0
	if enpc ~= 0 and gnpc ~= 0 then
		return enpc == gnpc
	end
	return ender == giver
end

-- Where a quest is handed in: uiMapID, x, y from the client's placement, or nil.
function QL.EndPoint(row)
	local res = QL.resolvedEnd and QL.resolvedEnd[row]
	if res then
		return res.mapID, res.x, res.y
	end
	return nil
end

-- Zone name of the turn-in, from its placement or the build-time guess.
function QL.EnderZoneName(row)
	local res = QL.resolvedEnd and QL.resolvedEnd[row]
	if res then
		local ok, info = pcall(C_Map.GetMapInfo, res.mapID)
		local name = ok and type(info) == "table" and QL.Plain(info.name) or nil
		if name then
			return name
		end
	end
	return (row[QL.F_ENDERZONE] or 0) ~= 0 and QL.Data().zones[row[QL.F_ENDERZONE]] or nil
end

function QL.ByLevel(a, b)
	if a[QL.F_LEVEL] ~= b[QL.F_LEVEL] then return a[QL.F_LEVEL] < b[QL.F_LEVEL] end
	return a[QL.F_TITLE] < b[QL.F_TITLE]
end

local function BuildIndex()
	QL.byZone, QL.zoneByName, QL.eventRows, QL.allRows, QL.searchText = {}, {}, {}, {}, {}
	local data = QL.Data()
	if type(data) ~= "table" then
		return
	end
	local zones = data.zones or {}
	for areaID, name in pairs(zones) do
		QL.zoneByName[name:lower()] = areaID
	end
	-- The client's placements (filled in over a few frames after enable by
	-- ResolveInChunks; the index is rebuilt when they are complete). The zone
	-- a giver lands in wins over the build-time guess.
	zoneOverride, QL.rowsByMap, QL.endRowsByMap = {}, {}, {}
	QL.resolved = QL.resolved or {}
	QL.resolvedEnd = QL.resolvedEnd or {}
	local mapArea = {}
	for _, row in ipairs(data.quests or {}) do
		local res = QL.resolved[row]
		if res then
			QL.rowsByMap[res.mapID] = QL.rowsByMap[res.mapID] or {}
			table.insert(QL.rowsByMap[res.mapID], row)
			local areaID = mapArea[res.mapID]
			if areaID == nil then
				local okI, info = pcall(C_Map.GetMapInfo, res.mapID)
				local name = okI and type(info) == "table" and QL.Plain(info.name) or nil
				areaID = name and QL.zoneByName[name:lower()] or false
				mapArea[res.mapID] = areaID
			end
			if areaID and areaID ~= QL.ZoneOf(row) then
				zoneOverride[row] = areaID
			end
		end
		local ender = QL.resolvedEnd[row]
		if ender then
			QL.endRowsByMap[ender.mapID] = QL.endRowsByMap[ender.mapID] or {}
			table.insert(QL.endRowsByMap[ender.mapID], row)
		end
	end
	for _, row in ipairs(data.quests or {}) do
		local zone = QL.ZoneOf(row)
		QL.searchText[row] = (row[QL.F_TITLE] .. " " .. row[QL.F_GIVER] .. " " .. (zones[zone] or "")):lower()
		if (row[QL.F_EVENT] or 0) ~= 0 then
			table.insert(QL.eventRows, row)
		elseif zone ~= 0 then
			QL.byZone[zone] = QL.byZone[zone] or {}
			table.insert(QL.byZone[zone], row)
			QL.allRows[#QL.allRows + 1] = row
		end
	end
	table.sort(QL.eventRows, QL.ByLevel)
	table.sort(QL.allRows, QL.ByLevel)
	for _, rows in pairs(QL.byZone) do
		table.sort(rows, QL.ByLevel)
	end
	-- Chain steps: follow the "previous quest" links back to the chain start.
	rowByID, QL.chainStep, chainTotal, nextInChain, QL.byDungeon = {}, {}, {}, {}, {}
	for _, row in ipairs(data.quests or {}) do
		rowByID[row[QL.F_ID]] = row
		if row[QL.F_DUNGEON] ~= 0 then
			QL.byDungeon[row[QL.F_DUNGEON]] = QL.byDungeon[row[QL.F_DUNGEON]] or {}
			table.insert(QL.byDungeon[row[QL.F_DUNGEON]], row)
		end
	end
	local function StepOf(row, depth)
		local step = QL.chainStep[row]
		if step then
			return step
		end
		local prevRow = (row[QL.F_PREV] or 0) ~= 0 and rowByID[row[QL.F_PREV]] or nil
		if prevRow and prevRow[QL.F_CHAIN] == row[QL.F_CHAIN] and depth < 60 then
			step = StepOf(prevRow, depth + 1) + 1
		else
			step = 1
		end
		QL.chainStep[row] = step
		return step
	end
	for _, row in ipairs(data.quests or {}) do
		if row[QL.F_CHAIN] ~= 0 then
			local step = StepOf(row, 0)
			if step > (chainTotal[row[QL.F_CHAIN]] or 0) then
				chainTotal[row[QL.F_CHAIN]] = step
			end
			local prev = row[QL.F_PREV] or 0
			if prev ~= 0 and rowByID[prev] and not nextInChain[prev] then
				nextInChain[prev] = row
			end
		end
	end
	local _, classFile = UnitClass("player")
	for mask, name in pairs(data.classes or {}) do
		if name == classFile then
			classBit = mask
		end
	end
	playerSide = UnitFactionGroup("player") == "Horde" and 2 or 1
end

-- Ask the client where every vanilla giver and turn-in is, a few hundred rows
-- per frame so login does not stall, then rebuild the index once.
local resolving = false
local resolveDone = false

local function ResolveInChunks(onDone)
	if resolving or resolveDone then
		return
	end
	local data = QL.Data()
	local rows = type(data) == "table" and data.quests or nil
	if not rows or not (C_Map.GetMapPosFromWorldPos and CreateVector2D and C_Map.GetMapInfoAtPosition and C_Map.GetMapRectOnMap) then
		resolveDone = true
		return
	end
	resolving = true
	QL.resolved = QL.resolved or {}
	QL.resolvedEnd = QL.resolvedEnd or {}
	local i, n = 1, #rows
	local function Step()
		local stop = math.min(i + 299, n)
		while i <= stop do
			local row = rows[i]
			if (row[QL.F_CONT] or -1) >= 0 and QL.resolved[row] == nil then
				QL.resolved[row] = QL.ResolveWorld(row[QL.F_CONT], row[QL.F_WX], row[QL.F_WY]) or false
			end
			if (row[QL.F_ENDERCONT] or -1) >= 0 and QL.resolvedEnd[row] == nil
				and not (row[QL.F_ENDERCONT] == row[QL.F_CONT] and row[QL.F_ENDERWX] == row[QL.F_WX] and row[QL.F_ENDERWY] == row[QL.F_WY]) then
				QL.resolvedEnd[row] = QL.ResolveWorld(row[QL.F_ENDERCONT], row[QL.F_ENDERWX], row[QL.F_ENDERWY]) or false
			end
			i = i + 1
		end
		if i <= n then
			C_Timer.After(0, Step)
		else
			resolving = false
			resolveDone = true
			onDone()
		end
	end
	Step()
end

-- step, total steps, next row (or nil) for a quest in a chain.
function QL.ChainInfo(row)
	if row[QL.F_CHAIN] == 0 or not QL.chainStep then
		return nil
	end
	return QL.chainStep[row] or 1, chainTotal[row[QL.F_CHAIN]] or 1, nextInChain[row[QL.F_ID]]
end

function QL.Eligible(row)
	local db = M.db
	if not db.otherFaction and row[QL.F_SIDE] ~= 0 and row[QL.F_SIDE] ~= 3 and row[QL.F_SIDE] ~= playerSide then
		return false
	end
	if not db.otherClass and row[QL.F_CLASS] ~= 0 and classBit and bit.band(row[QL.F_CLASS], classBit) == 0 then
		return false
	end
	local above = tonumber(db.levelAbove) or 0
	if above > 0 then
		local level = QL.Plain(UnitLevel("player")) or 60
		if row[QL.F_LEVEL] > level + above then
			return false
		end
	end
	return true
end

function QL.IsCompleted(questID)
	if C_QuestLog and C_QuestLog.IsQuestFlaggedCompleted then
		local ok, done = pcall(C_QuestLog.IsQuestFlaggedCompleted, questID)
		if ok and not IsSecret(done) then
			return done == true
		end
	end
	return false
end

function QL.IsOnQuest(questID)
	if C_QuestLog and C_QuestLog.IsOnQuest then
		local ok, on = pcall(C_QuestLog.IsOnQuest, questID)
		if ok and not IsSecret(on) then
			return on == true
		end
	end
	return false
end

-- A quest in the log whose objectives are all done.
local readyChecks = nil
function QL.IsReadyForTurnIn(questID)
	if not readyChecks then
		readyChecks = {}
		for _, name in ipairs({ "ReadyForTurnIn", "IsComplete" }) do
			if C_QuestLog and type(C_QuestLog[name]) == "function" then
				readyChecks[#readyChecks + 1] = C_QuestLog[name]
			end
		end
	end
	for _, fn in ipairs(readyChecks) do
		local ok, ready = pcall(fn, questID)
		if ok and not IsSecret(ready) and ready ~= nil then
			return ready == true
		end
	end
	return false
end

-- Quest log colouring: grey trivial, green easy, yellow fair, orange hard, red very hard.
function QL.DifficultyColor(level)
	if level <= 0 then
		return 0.75, 0.61, 0
	end
	if GetQuestDifficultyColor then
		local ok, color = pcall(GetQuestDifficultyColor, level)
		if ok and type(color) == "table" and color.r then
			return color.r, color.g, color.b
		end
	end
	local mine = QL.Plain(UnitLevel("player")) or 60
	local diff = level - mine
	if diff >= 5 then return 1, 0.1, 0.1 end
	if diff >= 3 then return 1, 0.5, 0.25 end
	if diff >= -2 then return 1, 0.82, 0 end
	local trivial = 5
	if mine >= 40 then trivial = 12 elseif mine >= 30 then trivial = 9 elseif mine >= 20 then trivial = 7 elseif mine >= 10 then trivial = 6 end
	if diff > -trivial then return 0.25, 0.75, 0.25 end
	return 0.5, 0.5, 0.5
end

