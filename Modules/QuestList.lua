		where = "Turn in: " .. row[F_ENDER]
		local _, ex, ey = EndPoint(row)
		if not ex and SameEnder(row) then
			_, ex, ey = GiverPoint(row)
		end
		if ex then
			where = where .. string.format("   %.1f, %.1f", ex * 100, ey * 100)
		end
		if entry.showZone then
			local endZone = EnderZoneName(row) or Data().zones[ZoneOf(row)]
			if endZone then
