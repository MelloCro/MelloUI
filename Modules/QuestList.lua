local eventFrame = CreateFrame("Frame")
eventFrame:SetScript("OnEvent", function(_, event, ...)
	if event == "PLAYER_ENTERING_WORLD" then
		-- Instance info and quest flags settle a moment after the load.
		C_Timer.After(2, function()
			if not QL.LearnEntrance() then
				C_Timer.After(6, QL.LearnEntrance)
			end
			DungeonSummary()
		end)
		if QL.pendingExit then
			C_Timer.After(1, QL.LearnEntranceOnExit)
		end
	elseif event == "UNIT_SPELLCAST_SUCCEEDED" then
		-- Hearthstone or Astral Recall out of the instance: the arrival point
		-- is not the door.
		local _, _, spellID = ...
		spellID = QL.Plain(spellID)
		if spellID == 8690 or spellID == 556 then
			QL.pendingExit = nil
		end
	elseif event == "PLAYER_LEAVING_WORLD" or event == "ZONE_CHANGED" or event == "ZONE_CHANGED_INDOORS" or event == "ZONE_CHANGED_NEW_AREA" then
		QL.RememberOutside()
	end
	if WorldMapFrame and WorldMapFrame:IsShown() then
		QL.Panel:Schedule()
	end
end)

local hooked = false

function M:OnInit(db)
	self.db = db
end

function M:OnEnable(db)
	self.db = db
	if type(MelloUI_QuestListData) ~= "table" then
		MelloUI:Print("Quest List: Media\\QuestListData.lua is missing; run Tools\\build_quest_list.py.")
		return
	end
	if not WorldMapFrame then
		return
	end
	if not QL.byZone then
		BuildIndex()
	end
	QL.Panel:Create()
	QL.Panel:Apply()
	QL.CreateProvider()
	QL.RefreshPins()
	ResolveInChunks(function()
		BuildIndex()
		if QL.Panel.frame and QL.Panel.frame:IsShown() then
			QL.Panel:Update()
		end
		QL.RefreshPins()
	end)
	if not hooked then
		hooked = true
		if WorldMapFrame.OnMapChanged then
			hooksecurefunc(WorldMapFrame, "OnMapChanged", function() QL.Panel:Update() end)
		end
	end
	-- the events go with the module's state (they ran on after a disable;
	-- audit 2026-09-22)
	eventFrame:RegisterEvent("QUEST_LOG_UPDATE")
	eventFrame:RegisterEvent("ZONE_CHANGED_NEW_AREA")
	eventFrame:RegisterEvent("PLAYER_LEVEL_UP")
	eventFrame:RegisterEvent("PLAYER_ENTERING_WORLD")
	eventFrame:RegisterEvent("PLAYER_LEAVING_WORLD")
	eventFrame:RegisterEvent("ZONE_CHANGED")
	eventFrame:RegisterEvent("ZONE_CHANGED_INDOORS")
	if eventFrame.RegisterUnitEvent then
		eventFrame:RegisterUnitEvent("UNIT_SPELLCAST_SUCCEEDED", "player")
	else
		eventFrame:RegisterEvent("UNIT_SPELLCAST_SUCCEEDED")
	end
	QL.StartOutsideTicker()
end

function M:OnDisable()
	eventFrame:UnregisterAllEvents()
	QL.StopOutsideTicker()
	if QL.Panel.frame then
		QL.Panel.frame:Hide()
	end
	if QL.Provider and WorldMapFrame then
		QL.Provider:RemoveAllData()
	end
end

function M:OnSettingChanged(key, value, db)
	self.db = db
	QL.Panel:Apply()
	QL.RefreshPins()
end

