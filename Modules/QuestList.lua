-- A panel attached to the right of the world map listing the quests that can
-- be picked up in a zone: how many of them you have done, and for each quest
-- its level, the quest giver and where to find it. Quests are grouped under
-- collapsible headers in the style of the quest log: one per quest chain,
-- then the single quests. Titles are coloured by difficulty like the quest
-- log, completed quests are greyed with a tick, and clicking a quest drops a
-- map pin on the giver.
--
-- The module is in three files: this one (data, placement, dungeon summary,
-- lifecycle, /qlmap), QuestListPanel.lua (the panel) and QuestListMap.lua
-- (map pins, entrances, transports and how entrances are learned).
--
-- Data: Media\QuestListData.lua, generated by Tools\build_quest_list.py from
-- Wowhead's Forever database, the vanilla server database and the map tables.
-- Quest givers that no database places (new Forever NPCs) get their position
-- from the Voice Over collector the first time you talk to them.
--------------------------------------------------------------------------------

