local lastInstance = nil

local function DungeonSummary()
	if not (M.isEnabled and M.db.dungeonSummary and byZone) then
		return
	end
	local okI, inInstance, kind = pcall(IsInInstance)
	if not okI or not inInstance or (kind ~= "party" and kind ~= "raid") then
		lastInstance = nil
		return
	end
	local okN, name = pcall(GetInstanceInfo)
	name = okN and Plain(name) or nil
	if not name or name == lastInstance then
		return
	end
	lastInstance = name
	local data = Data()
	local dungeonID
	for id, dname in pairs(data.dungeons or {}) do
		if dname:lower() == name:lower() then
			dungeonID = id
		end
	end
	if not dungeonID then
		return
	end
	local missing, inLog, done, total = {}, 0, 0, 0
	for _, row in ipairs(data.quests or {}) do
		if row[F_DUNGEON] == dungeonID and Eligible(row) then
			total = total + 1
			if IsCompleted(row[F_ID]) then
				done = done + 1
			elseif IsOnQuest(row[F_ID]) then
				inLog = inLog + 1
			else
				missing[#missing + 1] = row
			end
		end
	end
	if total == 0 then
		return
	end
	MelloUI:Print("%s: %d of %d quests done, %d in your log, %d not picked up.", name, done, total, inLog, #missing)
	for _, row in ipairs(data.quests or {}) do
		if row[F_DUNGEON] == dungeonID and Eligible(row) and IsOnQuest(row[F_ID]) and IsReadyForTurnIn(row[F_ID]) and (row[F_ENDER] or "") ~= "" then
			local endZone = EnderZoneName(row) or Data().zones[ZoneOf(row)]
			print(string.format("   |cffffd200%s|r is ready: turn in to %s%s", row[F_TITLE], row[F_ENDER], endZone and (" in " .. endZone) or ""))
		end
	end
	table.sort(missing, ByLevel)
	for i, row in ipairs(missing) do
		if i > 12 then
			print(string.format("   ... and %d more; see the Dungeons tab of the quest list.", #missing - 12))
			break
		end
		local r, g, b = DifficultyColor(row[F_LEVEL])
		local zone = data.zones[row[F_GIVERZONE]] or data.zones[row[F_ZONE]]
		local from = row[F_GIVER] ~= "" and row[F_GIVER] or "giver unknown"
		print(string.format("   |cff%02x%02x%02x%s|r (%d)  -  %s%s", r * 255, g * 255, b * 255, row[F_TITLE], row[F_LEVEL],
			from, zone and (", " .. zone) or ""))
	end
end

