"""
Build the modern look's class portraits (1.2.0; the user, 2026-10-22: "new Portrait Icons for the Default Modern UI,
the Oldschool still uses the ones we created for it, new class icons should fit the Default Modern theme ... fit the
dimensions of the original WoW Unitframe Portait icons"; their go to BuildData/output/ai_art/class_portraits/
portrait_sketch.html, "put them in the game").

The art: ChatGPT's 3 x 3 sheet, cut by masters/class_portraits/cut_portraits.py into one square per class
(MelloUI-BuildData/masters/class_portraits/src/<CLASS>.png: the emblem centred, the background out to the corners).
Square and full-bleed, as the game's own portraits are: the unit frame cuts them to a circle (the player's 60 x 60, the
target's and focus's 58 x 58, the small frames' 37 x 37, Blizzard_UnitFrame), its ring over the edge.

Each class at SIZES px (the client draws an addon TGA bilinear with no mipmaps: Modules/ClassIcons.lua picks the copy
nearest a portrait's size on the screen, so it is read at about a texel a pixel), a 32-bit TGA, its master under
MelloUI-BuildData/masters/Media/Icons/ClassModern/ and a byte copy in the addon's Media/Icons/ClassModern/ so it ships
at once (texture_pack.py ship keeps the masters' bytes: STAY_TGA). Writes Media/ClassPortraits.lua, the paths by class
and size (MelloUI_ClassPortraits). Deterministic: the same art gives the same bytes.

    python Tools/make_class_portraits.py            write them
    python Tools/make_class_portraits.py --check    exit 1 unless all are up to date
"""
import io
import os
import sys

from PIL import Image
from paths import ADDON_MEDIA, MASTERS, master

SRC = os.path.join(os.path.dirname(MASTERS), "masters", "class_portraits", "src")
CLASSES = ("WARRIOR", "PALADIN", "HUNTER", "ROGUE", "PRIEST", "SHAMAN", "MAGE", "WARLOCK", "DRUID")
SIZES = (64, 96, 128)
OUT = ("Icons", "ClassModern")
LUA = os.path.join(os.path.dirname(ADDON_MEDIA), "Media", "ClassPortraits.lua")
PATH = "Interface\\\\AddOns\\\\MelloUI\\\\Media\\\\Icons\\\\ClassModern\\\\%s_%d"


def tga(img):
    buf = io.BytesIO()
    img.save(buf, format="TGA")
    return buf.getvalue()


def lua():
    lines = ["-- Generated by Tools/make_class_portraits.py. Do not edit by hand.",
             "-- The modern look's class portraits (square; the unit frames cut them round): each class at these sizes",
             "-- (px), Modules/ClassIcons.lua picking the one nearest a portrait's size on the screen.",
             "",
             "MelloUI_ClassPortraits = {",
             "\tsizes = { %s }," % ", ".join(str(s) for s in SIZES),
             "\tclasses = {"]
    for c in CLASSES:
        lines.append("\t\t%s = { %s }," % (c, ", ".join('[%d] = "%s"' % (s, PATH % (c, s)) for s in SIZES)))
    lines += ["\t},", "}", ""]
    return "\n".join(lines).encode("utf-8")


def main():
    bad = [a for a in sys.argv[1:] if a != "--check"]
    if bad:
        print("unknown argument: %s (nothing written)\n" % " ".join(bad))
        print(__doc__[__doc__.index("    python Tools/"):].rstrip())
        return 2
    check = "--check" in sys.argv
    files = []
    for c in CLASSES:
        src = Image.open(os.path.join(SRC, c + ".png")).convert("RGB")
        for s in SIZES:
            img = src.resize((s, s), Image.LANCZOS).convert("RGBA")
            data = tga(img)
            name = "%s_%d.tga" % (c, s)
            files.append(((master(*OUT, name), os.path.join(ADDON_MEDIA, *OUT, name)), data))
    files.append(((LUA,), lua()))
    stale = []
    for paths, data in files:
        for path in paths:
            if check:
                try:
                    with open(path, "rb") as f:
                        if f.read() != data:
                            stale.append(path)
                except OSError:
                    stale.append(path)
                continue
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(data)
    if check:
        for path in stale:
            print("stale:", os.path.normpath(path))
        print("ok" if not stale else "STALE")
        return 1 if stale else 0
    print("%d portraits x %d sizes written (masters + Media/Icons/ClassModern), Media/ClassPortraits.lua"
          % (len(CLASSES), len(SIZES)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
