"""The Supporters page's Contributors (Media/ContributorsData.lua): the people whose pull requests were merged on
MelloUI's GitHub, with what they helped with -- code, translations (a pull request that changes only
MelloUI_Languages/), or both -- the most merged first. Tools/release.py runs it before each release, as it refreshes
the supporters from Discord; it never refuses a release.

    python Tools/contributors.py            write the file from GitHub (gh pr list: merged pull requests)
    python Tools/contributors.py --dry-run  print what it would write

Left out: the repository's owner, bots, and every login in Tools/contributors-exclude.txt (one a line). Tools never
ship.
"""
import argparse
import datetime
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "Media", "ContributorsData.lua")
EXCLUDE = os.path.join(HERE, "contributors-exclude.txt")
OWNER = "MelloCro"
LANGUAGES = "MelloUI_Languages/"

HEAD = """-- Generated by Tools/contributors.py from the pull requests merged on MelloUI's GitHub: the people whose code and
-- translations are in MelloUI, the most merged first, shown on the configurator's Supporters page
-- (Core/SupportersHall.lua). Do not edit by hand: a name to leave out goes in Tools/contributors-exclude.txt.
"""


def kind_of(paths):
    """'translations' for a pull request that changes only the language files, else 'code'."""
    paths = [p for p in paths if p]
    if paths and all(p.startswith(LANGUAGES) for p in paths):
        return "translations"
    return "code"


def build(prs, exclude=()):
    """[(login, what, merged)] from [{who, bot, files}], the most merged first, then by name. `what`: 'code',
    'translations' or 'code and translations'."""
    skip = {OWNER.lower()} | {x.lower() for x in exclude}
    people = {}
    for pr in prs:
        who = pr.get("who") or ""
        if not who or pr.get("bot") or who.endswith("[bot]") or who.lower() in skip:
            continue
        p = people.setdefault(who, {"n": 0, "kinds": set()})
        p["n"] += 1
        p["kinds"].add(kind_of(pr.get("files") or []))
    out = []
    for who, p in people.items():
        kinds = p["kinds"]
        what = "code and translations" if len(kinds) == 2 else next(iter(kinds))
        out.append((who, what, p["n"]))
    out.sort(key=lambda r: (-r[2], r[0].lower()))
    return out


def lua_quote(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def render(rows, today):
    lines = [HEAD, "MelloUI_Contributors = {\n", '\tupdated = "%s",\n' % today]
    for who, what, n in rows:
        lines.append('\t{ name = "%s", what = "%s", merged = %d },\n' % (lua_quote(who), what, n))
    lines.append("}\n")
    return "".join(lines)


def fetch():
    """[{who, bot, files}] of every merged pull request (gh, MelloUI's own repository)."""
    r = subprocess.run(["gh", "pr", "list", "--state", "merged", "--limit", "1000", "--json", "author,files"],
                       cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=120)
    if r.returncode != 0:
        raise RuntimeError((r.stderr or r.stdout or "gh failed").strip().splitlines()[-1])
    out = []
    for pr in json.loads(r.stdout or "[]"):
        author = pr.get("author") or {}
        out.append({"who": author.get("login"), "bot": bool(author.get("is_bot")),
                    "files": [f.get("path") for f in (pr.get("files") or [])]})
    return out


def excluded():
    if not os.path.isfile(EXCLUDE):
        return []
    with open(EXCLUDE, encoding="utf-8") as fh:
        return [line.strip() for line in fh if line.strip() and not line.startswith("#")]


def main(argv=None):
    ap = argparse.ArgumentParser(description="The Supporters page's Contributors, from GitHub's merged pull requests.")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)
    try:
        rows = build(fetch(), excluded())
    except (OSError, RuntimeError, ValueError, subprocess.TimeoutExpired) as exc:
        print("contributors not refreshed (%s) -- the list stays as it is" % exc)
        return 1
    text = render(rows, datetime.date.today().isoformat())
    names = ", ".join("%s (%s)" % (who, what) for who, what, _ in rows) or "none"
    old = None
    if os.path.isfile(OUT):
        with open(OUT, encoding="utf-8") as fh:
            old = fh.read()
    # (the date alone changed: the file stays, so a release with the same people changes nothing)
    same = old is not None and old.split("\tupdated")[0] == text.split("\tupdated")[0] \
        and old[old.index("\n", old.index("\tupdated")):] == text[text.index("\n", text.index("\tupdated")):]
    if a.dry_run:
        print("contributors [DRY RUN, nothing written]: %s%s" % (names, " (unchanged)" if same else ""))
        return 0
    if same:
        print("contributors unchanged: %s" % names)
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("contributors written: %s" % names)
    return 0


if __name__ == "__main__":
    sys.exit(main())
