function Record.Slash(rest)
	local word, name = (rest or ""):match("^(%S*)%s*(.-)%s*$")
	local chars = Record.Store().chars
	if word == "forget" and name ~= "" then
		local want, hit, hits = name:lower(), nil, 0
		for key, c in pairs(chars) do
			if key:lower() == want then
				hit, hits = key, 1
				break
			elseif type(c) == "table" and type(c.name) == "string" and c.name:lower() == want then
				hit, hits = key, hits + 1
			end
		end
		if hits == 0 then
			MelloUI:Print(ALTS.unknown, name)
		elseif hits > 1 then
			MelloUI:Print(ALTS.twice, name)
		elseif hit == Record.Me() then
			MelloUI:Print(ALTS.you, hit)
		else
			chars[hit] = nil
			Record.order = nil
			MelloUI:Print(ALTS.forgot, hit)
		end
		return
	elseif word ~= "" then
		MelloUI:Print(ALTS.usage)
		return
	end
	local keys = {}
	for key, c in pairs(chars) do
		if type(c) == "table" then
			keys[#keys + 1] = key
		end
	end
	if #keys == 0 then
		MelloUI:Print(ALTS.none)
		return
	end
	table.sort(keys)
	MelloUI:Print(ALTS.head)
	local classNames = rawget(_G, "LOCALIZED_CLASS_NAMES_MALE")
	for _, key in ipairs(keys) do
		local c = chars[key]
		local class = type(classNames) == "table" and classNames[c.class] or c.class or "?"
		local seen = type(c.seen) == "number" and date("%Y-%m-%d", c.seen) or "?"
		MelloUI:Print(ALTS.line, key, tostring(c.level or "?"), class, RecordCount(c.done), RecordCount(c.log), seen)
	end
end

