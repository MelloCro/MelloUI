function M:OnEnable(db)
	self.db = db
	if type(MelloUI_QuestListData) ~= "table" then
		MelloUI:Print("Quest List: its quest data (Media\\QuestListData.lua) is missing, so the list stays off. Reinstall MelloUI from its download, copying every folder.")
		return
	end
	if not WorldMapFrame then
		return
	end
	-- the quest tooltips (QuestListTips.lua): their two post-calls, once;
	-- the log may have changed while the module was off (QUEST_LOG_UPDATE,
	-- which counts the changes, is registered below with the module's
	-- other events)
	QL.logChanges = QL.logChanges + 1
	if QL.InstallTips then
		QL.InstallTips()
	end
	if not QL.byZone then
		BuildIndex()
	else
		playerSide = QL.PlayerSide()   -- a faction picked while the list was off
	end
	QL.Panel:Create()
	QL.Panel:Apply()
	QL.CreateProvider()
	QL.RefreshPins()
	ResolveInChunks(function()
		BuildIndex()
		if QL.Panel.frame and QL.Panel.frame:IsShown() then
			QL.Panel:Update()
		end
		QL.RefreshPins()
	end)
	if not hooked then
		hooked = true
		if WorldMapFrame.OnMapChanged then
			-- quiet: a map that lists the same quests is not laid out again
			hooksecurefunc(WorldMapFrame, "OnMapChanged", function() QL.Panel:Update(true) end)
		end
		-- the page is the addon's own frame (in the layer over the map): its
		-- search text goes a while after it hides
		if QL.Panel.frame then
			Perf.HookScript(QL.Panel.frame, "OnHide", PanelHidden)
		end
	end
	-- the events go with the module's state (they ran on after a disable;
	-- audit 2026-09-22)
	eventFrame:RegisterEvent("QUEST_LOG_UPDATE")
	eventFrame:RegisterEvent("ZONE_CHANGED_NEW_AREA")
	eventFrame:RegisterEvent("PLAYER_LEVEL_UP")
	eventFrame:RegisterEvent("PLAYER_ENTERING_WORLD")
	eventFrame:RegisterEvent("PLAYER_LEAVING_WORLD")
	eventFrame:RegisterEvent("ZONE_CHANGED")
	eventFrame:RegisterEvent("ZONE_CHANGED_INDOORS")
	eventFrame:RegisterEvent("PLAYER_LOGOUT")   -- (the account record: QL.Record)
	-- (what the quest givers offer: QL.Offers)
	for _, event in ipairs({ "GOSSIP_SHOW", "QUEST_GREETING", "QUEST_DETAIL", "QUEST_TURNED_IN", "SKILL_LINES_CHANGED" }) do
		eventFrame:RegisterEvent(event)
	end
	if eventFrame.RegisterUnitEvent then
		eventFrame:RegisterUnitEvent("UNIT_SPELLCAST_SUCCEEDED", "player")
		eventFrame:RegisterUnitEvent("UNIT_FACTION", "player")
	else
		eventFrame:RegisterEvent("UNIT_SPELLCAST_SUCCEEDED")
		eventFrame:RegisterEvent("UNIT_FACTION")
	end
	-- a Neutral character picking its faction (Zephras Isle, 0.14.0),
	-- registered as Route registers it: only where this client has the
	-- event (a RegisterEvent of an unknown one raises)
	pcall(eventFrame.RegisterEvent, eventFrame, "NEUTRAL_FACTION_SELECT_RESULT")
	QL.StartOutsideTicker()
	if QL.Objectives then
		QL.Objectives.GameMarks()   -- (the game's own quest areas off while the objective marks are on)
	end
end

function M:OnDisable()
	eventFrame:UnregisterAllEvents()
	QL.StopOutsideTicker()
	-- the page and its switch gone, the game's list given back
	if QL.Panel.frame then
		QL.Panel:Sync(true)
	end
	-- off with the map closed, the panel's OnHide never comes: the search
	-- text goes now (the first search after an enable makes it again)
	if QL.searchText then
		ForgetSearchText()
	end
	if QL.Provider and WorldMapFrame then
		QL.Provider:RemoveAllData()
	end
	if QL.Objectives then
		QL.Objectives.MiniSoon()   -- (off: the minimap's marks go)
		QL.Objectives.GameMarks()   -- (and the game's own quest areas come back)
	end
end

function M:OnSettingChanged(key, value, db)
	self.db = db
	if key == "tipQuestItems" or key == "tipTurnIn" or key == "tipCharacters" then
		return   -- read by the next tooltip; the panel and the pins show neither
	end
	QL.Panel:Apply()
	QL.RefreshPins()
	if QL.Objectives then
		QL.Objectives.MiniSoon()   -- (the minimap's marks: their switches, the tracked-only choice)
		QL.Objectives.GameMarks()   -- (the game's own quest areas: off while the marks are on)
	end
end

-- /qlmap: why pins are (not) on the map shown.
SLASH_MELLOQUESTMAP1 = "/qlmap"
SlashCmdList.MELLOQUESTMAP = function(msg)
	local data = QL.Data()
	if type(data) ~= "table" then
		MelloUI:Print("Quest List: its quest data (Media\\QuestListData.lua) is missing. Reinstall MelloUI from its download, copying every folder.")
		return
	end
	msg = (msg or ""):gsub("^%s+", ""):gsub("%s+$", "")
	local cmd, rest = msg:match("^(%S+)%s*(.-)$")
	cmd = cmd and cmd:lower()
	if cmd == "dock" or cmd == "zeppelin" then
		-- /qlmap dock Boat to Auberdine [| Alliance|Horde]   (stand on the dock)
		if rest == "" then
			MelloUI:Print("Stand on the dock and type:  /qlmap dock Boat to Auberdine   (add  | horde  or  | alliance  for a faction-only route; default neutral).")
			return
		end
		local label, side = rest:match("^(.-)%s*|%s*(%a+)$")
		label = label or rest
		local faction = 0
		if side and side:lower() == "alliance" then faction = 1 elseif side and side:lower() == "horde" then faction = 2 end
		local mapID, x, y, dock = QL.PlayerMapPoint()
		if not mapID then
			MelloUI:Print("Cannot read your position here.")
			return
		end
		QL.LearnedStore("transports")[label] = { mapID = mapID, x = x, y = y, dock = dock, kind = cmd == "zeppelin" and 2 or 1, faction = faction }
		MelloUI:Print("Recorded '%s' at %s (%.1f, %.1f). Sail there and type  /qlmap arrive %s  to link the destination map.", label, dock, x * 100, y * 100, label)
		QL.RefreshPins()
	elseif cmd == "arrive" then
		local l = rest ~= "" and QL.LearnedStore("transports")[rest]
		if not l then
			MelloUI:Print("No recorded dock called '%s'.", rest)
			return
		end
		local mapID = QL.PlayerMapPoint()
		if mapID then
			l.destMapID = mapID
			MelloUI:Print("'%s' now opens %s when clicked.", rest, QL.ZoneNameForMap(mapID) or tostring(mapID))
		end
	elseif cmd == "entrance" then
		-- /qlmap entrance Hall of Thanes [| raid]   (stand at the entrance)
		if rest == "" then
			MelloUI:Print("Stand at the entrance and type:  /qlmap entrance Hall of Thanes   (add  | raid  for a raid).")
			return
		end
		local name, kind = rest:match("^(.-)%s*|%s*(%a+)$")
		name = name or rest
		local mapID, x, y = QL.PlayerMapPoint()
		if not mapID then
			MelloUI:Print("Cannot read your position here.")
			return
		end
		QL.LearnedStore("entrances")[name] = { mapID = mapID, x = x, y = y, raid = kind ~= nil and kind:lower() == "raid" }
		MelloUI:Print("Recorded the entrance of %s at %.1f, %.1f.", name, x * 100, y * 100)
		QL.RefreshPins()
	elseif cmd == "remove" then
		local removed = false
		if QL.LearnedStore("transports")[rest] then
			QL.LearnedStore("transports")[rest] = nil
			removed = true
		end
		if QL.LearnedStore("entrances")[rest] then
			QL.LearnedStore("entrances")[rest] = nil
			removed = true
		end
		MelloUI:Print(removed and ("Removed '" .. rest .. "'.") or ("Nothing recorded as '" .. rest .. "'."))
		QL.RefreshPins()
	elseif cmd == "list" then
		MelloUI:Print("Recorded pins:")
		for name, l in pairs(QL.LearnedStore("entrances")) do
			print(string.format("   entrance  %s  (%s %.1f, %.1f)", name, QL.ZoneNameForMap(l.mapID) or "?", l.x * 100, l.y * 100))
		end
		for label, l in pairs(QL.LearnedStore("transports")) do
			print(string.format("   dock  %s  (%s %.1f, %.1f)%s", label, QL.ZoneNameForMap(l.mapID) or "?", l.x * 100, l.y * 100,
				l.destMapID and ("  ->  " .. (QL.ZoneNameForMap(l.destMapID) or "?")) or ""))
		end
		return
	elseif cmd and cmd ~= "" then
		MelloUI:Print("/qlmap  (diagnostics)  |  /qlmap dock <label> [| alliance|horde]  |  /qlmap zeppelin <label>  |  /qlmap arrive <label>  |  /qlmap entrance <name> [| raid]  |  /qlmap remove <name>  |  /qlmap list")
		return
	end
	if cmd then
		return
	end
	MelloUI:Print("Quest List map pins")
	print("   provider: " .. tostring(QL.Provider ~= nil) .. "   marks' layer: " .. tostring(QL.Marks and QL.Marks.layer ~= nil)
		.. "   GetMapPosFromWorldPos: " .. tostring(C_Map.GetMapPosFromWorldPos ~= nil) .. "   CreateVector2D: " .. tostring(CreateVector2D ~= nil))
	print(string.format("   data: %d entrances, %d transports, %d learned", #(data.entrances or {}), #(data.transports or {}),
		(function() local n = 0 for _ in pairs(QL.LearnedStore("entrances")) do n = n + 1 end return n end)()))
	print(string.format("   options: pins %s, entrances %s, transports %s, badges %s",
		tostring(M.db.mapPins), tostring(M.db.entrancePins), tostring(M.db.transportPins), tostring(M.db.zoneBadges)))
	if QL.lastPinInfo then
		print(string.format("   last refresh: map %s (%s), type %s", tostring(QL.lastPinInfo.mapID), tostring(QL.lastPinInfo.name), tostring(QL.lastPinInfo.mapType)))
		local client = QL.ClientEntrances(QL.lastPinInfo.mapID)
		print(string.format("   client entrance list for this map: %s, %d entries", tostring(C_EncounterJournal and C_EncounterJournal.GetDungeonEntrancesForMap ~= nil), #client))
		for i, e in ipairs(client) do
			if i > 8 then break end
			print(string.format("      %s at %.1f, %.1f", e.name, e.x * 100, e.y * 100))
		end
		local pois = QL.ClientPOIs(QL.lastPinInfo.mapID)
		print(string.format("   points of interest the map shows: %d", #pois))
		for i, poi in ipairs(pois) do
			if i > 12 then
				print("      ... " .. (#pois - 12) .. " more")
				break
			end
			print(string.format("      %s%s at %.1f, %.1f  [%s]", poi.name, QL.IsEntrancePOI(poi) and " (instance)" or "", poi.x * 100, poi.y * 100, poi.atlas))
		end
	else
		print("   no refresh yet (open the map).")
	end
	if QL.MarkList then
		local marks, kinds = QL.MarkList(), {}
		for _, m in ipairs(marks) do
			kinds[m.kind] = (kinds[m.kind] or 0) + 1
		end
		local parts = {}
		for k, v in pairs(kinds) do parts[#parts + 1] = k .. " " .. v end
		print("   marks on the map: " .. #marks .. (#marks > 0 and (" (" .. table.concat(parts, ", ") .. ")") or ""))
	end
	-- the layers: the marks and the page over the map's picture (their layer a strata up)
	local function Layer(name, f)
		if f then
			print(string.format("   %s: %s %d%s%s", name, f:GetFrameStrata(), f:GetFrameLevel(),
				f.IsFrameBuffer and f:IsFrameBuffer() and ", frame buffer" or "", f:IsVisible() and "" or ", hidden"))
		end
	end
	Layer("map", WorldMapFrame)
	Layer("layer over the map", MelloUI.mapLayer)
	Layer("page", QL.Panel.frame)
	Layer("marks' layer", QL.Marks and QL.Marks.clip)
	for _, err in ipairs(QL.lastPinErrors) do
		print("   |cffff4040error|r " .. err)
	end
	local trace = QL.lastPointTrace
	for i, line in ipairs(trace) do
		if i > 8 then
			print("   ... " .. (#trace - 8) .. " more")
			break
		end
		print("   " .. line)
	end
	-- Probe the API with the first entrance.
	local e = data.entrances and data.entrances[1]
	if e and C_Map.GetMapPosFromWorldPos and CreateVector2D then
		local ok, uiMapID, pos = pcall(C_Map.GetMapPosFromWorldPos, e[3], CreateVector2D(e[4], e[5]))
		local x, y = QL.VectorXY(pos)
		print(string.format("   probe %s at (%d, %.0f, %.0f): ok %s, map %s, pos %s (%s, %s)", e[2], e[3], e[4], e[5],
			tostring(ok), tostring(uiMapID), type(pos), tostring(x), tostring(y)))
	end
end

