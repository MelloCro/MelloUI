local function RowByID()
	if not rowByID then
		rowByID = {}
		local data = MelloUI_QuestListData
		for _, row in ipairs(type(data) == "table" and data.quests or {}) do
			rowByID[row[QL.F_ID]] = row
		end
	end
	return rowByID
end
