-- The search box's text for every quest, lower-cased "title giver zone":
-- made on the first search rather than with the index, and let go a while
-- after the panel hides with the box empty (memory audit, 2026-09-24: 0.8 MB
-- held from login, whether the box is used or not). QuestListPanel reads
-- QL.searchText[row]; the first read fills the whole table, from the zones
-- as the index has them.
local PanelHidden
local searchTextMeta = {}
function searchTextMeta.__index(t, row)
	setmetatable(t, nil)   -- once: a row it has no text for stays nil
	local data = QL.Data()
	if type(data) ~= "table" then
		return nil
	end
	local zones = data.zones or {}
	for _, r in ipairs(data.quests or {}) do
		t[r] = (r[QL.F_TITLE] .. " " .. r[QL.F_GIVER] .. " " .. (zones[QL.ZoneOf(r)] or "")):lower()
	end
	-- made while the map is closed (the panel lays itself out on a setting
	-- change even then): no OnHide is coming, so the wait starts here
	local frame = QL.Panel and QL.Panel.frame
	if frame and not frame:IsVisible() then
		PanelHidden()
	end
	return rawget(t, row)
end

local function ForgetSearchText()
	QL.searchText = setmetatable({}, searchTextMeta)
end

-- A term in the panel's search box: the box keeps it when the map closes,
-- and the panel searches it again as soon as it shows.
local function Searching(frame)
	local box = frame.search
	local term = box and box.GetText and box:GetText()
	return type(term) == "string" and term:find("%S") ~= nil
end

-- Let the text go once the panel has been hidden a while with the box empty
-- (not at once: the map is opened and closed all the time; and not with a
-- term left in the box, which every opening searches again -- it was made
-- afresh, 1 MB, on each opening that way; review, 2026-09-24).
local SEARCH_TEXT_KEEP = 30   -- seconds
local panelHides = 0
function PanelHidden()
	panelHides = panelHides + 1
	local hide = panelHides
	C_Timer.After(SEARCH_TEXT_KEEP, function()
		local frame = QL.Panel and QL.Panel.frame
		if hide ~= panelHides or (frame and frame:IsVisible()) then
			return
		end
		-- kept for a term in the box, unless the panel itself is off (the
		-- module is): nothing searches until it is on again
		if frame and frame:IsShown() and Searching(frame) then
			return
		end
		ForgetSearchText()
	end)
end

local function BuildIndex()
	QL.byZone, QL.zoneByName, QL.eventRows, QL.allRows = {}, {}, {}, {}
	ForgetSearchText()
	local data = QL.Data()
	if type(data) ~= "table" then
		return
	end
	local zones = data.zones or {}
	for areaID, name in pairs(zones) do
		QL.zoneByName[name:lower()] = areaID
	end
	-- The client's placements (filled in over a few frames after enable by
	-- ResolveInChunks; the index is rebuilt when they are complete). The zone
	-- a giver lands in wins over the build-time guess.
	zoneOverride, QL.rowsByMap, QL.endRowsByMap = {}, {}, {}
	QL.resolved = QL.resolved or {}
	QL.resolvedEnd = QL.resolvedEnd or {}
	local mapArea = {}
	for _, row in ipairs(data.quests or {}) do
		local n = QL.resolved[row]
		if n then
			local mapID = placeMap[n]
			QL.rowsByMap[mapID] = QL.rowsByMap[mapID] or {}
			table.insert(QL.rowsByMap[mapID], row)
			local areaID = mapArea[mapID]
			if areaID == nil then
				local okI, info = pcall(C_Map.GetMapInfo, mapID)
				local name = okI and type(info) == "table" and QL.Plain(info.name) or nil
				areaID = name and QL.zoneByName[name:lower()] or false
				mapArea[mapID] = areaID
			end
			if areaID and areaID ~= QL.ZoneOf(row) then
				zoneOverride[row] = areaID
			end
		end
		local e = QL.resolvedEnd[row]
		if e then
			local mapID = placeMap[e]
			QL.endRowsByMap[mapID] = QL.endRowsByMap[mapID] or {}
			table.insert(QL.endRowsByMap[mapID], row)
		end
	end
	for _, row in ipairs(data.quests or {}) do
		local zone = QL.ZoneOf(row)
		if (row[QL.F_EVENT] or 0) ~= 0 then
			table.insert(QL.eventRows, row)
		elseif zone ~= 0 then
			QL.byZone[zone] = QL.byZone[zone] or {}
			table.insert(QL.byZone[zone], row)
			QL.allRows[#QL.allRows + 1] = row
		end
	end
	table.sort(QL.eventRows, QL.ByLevel)
	table.sort(QL.allRows, QL.ByLevel)
	for _, rows in pairs(QL.byZone) do
		table.sort(rows, QL.ByLevel)
	end
	-- Chain steps: follow the "previous quest" links back to the chain start.
	QL.chainStep, chainTotal, nextInChain, QL.byDungeon = {}, {}, {}, {}
	RowByID()   -- the by-ID lookup the steps below follow
	for _, row in ipairs(data.quests or {}) do
		if row[QL.F_DUNGEON] ~= 0 then
			QL.byDungeon[row[QL.F_DUNGEON]] = QL.byDungeon[row[QL.F_DUNGEON]] or {}
			table.insert(QL.byDungeon[row[QL.F_DUNGEON]], row)
		end
	end
	local function StepOf(row, depth)
		local step = QL.chainStep[row]
		if step then
			return step
		end
		local prevRow = (row[QL.F_PREV] or 0) ~= 0 and rowByID[row[QL.F_PREV]] or nil
		if prevRow and prevRow[QL.F_CHAIN] == row[QL.F_CHAIN] and depth < 60 then
			step = StepOf(prevRow, depth + 1) + 1
		else
			step = 1
		end
		QL.chainStep[row] = step
		return step
	end
	for _, row in ipairs(data.quests or {}) do
		if row[QL.F_CHAIN] ~= 0 then
			local step = StepOf(row, 0)
			if step > (chainTotal[row[QL.F_CHAIN]] or 0) then
				chainTotal[row[QL.F_CHAIN]] = step
			end
			local prev = row[QL.F_PREV] or 0
			if prev ~= 0 and rowByID[prev] and not nextInChain[prev] then
				nextInChain[prev] = row
			end
		end
	end
	local _, classFile = UnitClass("player")
	for mask, name in pairs(data.classes or {}) do
		if name == classFile then
			classBit = mask
		end
	end
	-- (the eight races the masks know; a newer one is never left out by them)
	local okR, _, _, raceID = pcall(UnitRace, "player")
	raceID = okR and QL.Plain(raceID) or nil
	raceBit = (type(raceID) == "number" and raceID >= 1 and raceID <= 8) and 2 ^ (raceID - 1) or nil
	playerSide = QL.PlayerSide()
end

-- The player's side as the data writes it: 1 Alliance, 2 Horde, and 0 while
-- Neutral (a new Skyborne character before the faction choice): the quests
-- open to both factions only (the Zephras Isle fix, 0.14.0; it counted as
-- Alliance). Route's one side helper (Route.PlayerSide, a plain function
-- that answers with Route off too), so the list, Route and Services agree.
-- (Route.lua loads with every MelloUI; a stripped test world without it
-- counts as Alliance, as before. The rows' own test stays Eligible's: a
-- quest row writes "both" as 0 or 3.)
function QL.PlayerSide()
	local R = MelloUI.Route
	return R and R.PlayerSide and R.PlayerSide() or 1
end

-- The faction picked (or a PvP flag, which comes the same way): the list and
-- the pins follow a new side at once, not after a reload
function QL.SideChanged()
	if playerSide == nil then
		return   -- no index yet: it reads the side when it is made
	end
	local side = QL.PlayerSide()
	if side ~= playerSide then
		playerSide = side
		QL.RefreshPins()
	end
end

-- Ask the client where every vanilla giver and turn-in is, a few hundred rows
-- per frame so login does not stall, then rebuild the index once.
local resolving = false
local resolveDone = false

local function ResolveInChunks(onDone)
	if resolving or resolveDone then
		return
	end
	local data = QL.Data()
	local rows = type(data) == "table" and data.quests or nil
	if not rows or not (C_Map.GetMapPosFromWorldPos and CreateVector2D and C_Map.GetMapInfoAtPosition and C_Map.GetMapRectOnMap) then
		resolveDone = true
		return
	end
	resolving = true
	QL.resolved = QL.resolved or {}
	QL.resolvedEnd = QL.resolvedEnd or {}
	local i, n = 1, #rows
	-- (0.19.2: a time budget per frame, not 300 rows: a row's map conversions
	-- cost about 0.1 ms, so 300 rows were up to 55 ms a frame, 18 frames
	-- running, right after login -- the client's budget for an addon is a
	-- 1000 ms burst refilled at 500 ms a second, and once it is spent the
	-- game cannot call MelloUI's hooks: the user's "attempt to call a nil
	-- value" flood, 2026-10-05. QL.RESOLVE_MS a frame stays far under it)
	local function Step()
		local t0 = debugprofilestop()
		while i <= n do
			local row = rows[i]
			if (row[QL.F_CONT] or -1) >= 0 and QL.resolved[row] == nil then
				QL.resolved[row] = StorePlacement(QL.ResolveWorld(row[QL.F_CONT], row[QL.F_WX], row[QL.F_WY]))
			end
			if (row[QL.F_ENDERCONT] or -1) >= 0 and QL.resolvedEnd[row] == nil
				and not (row[QL.F_ENDERCONT] == row[QL.F_CONT] and row[QL.F_ENDERWX] == row[QL.F_WX] and row[QL.F_ENDERWY] == row[QL.F_WY]) then
				QL.resolvedEnd[row] = StorePlacement(QL.ResolveWorld(row[QL.F_ENDERCONT], row[QL.F_ENDERWX], row[QL.F_ENDERWY]))
			end
			i = i + 1
			if debugprofilestop() - t0 >= QL.RESOLVE_MS then
				break
			end
		end
		if i <= n then
			C_Timer.After(0, Step)
		else
			resolving = false
			resolveDone = true
			onDone()
		end
	end
	Step()
end

-- step, total steps, next row (or nil) for a quest in a chain.
function QL.ChainInfo(row)
	if row[QL.F_CHAIN] == 0 or not QL.chainStep then
		return nil
	end
	return QL.chainStep[row] or 1, chainTotal[row[QL.F_CHAIN]] or 1, nextInChain[row[QL.F_ID]]
end

function QL.Eligible(row)
	local db = M.db
	-- (hidden by hand and not taken: off the map, off the list unless asked for)
	if not db.showHidden and QL.IsHidden(row[QL.F_ID]) and not QL.IsOnQuest(row[QL.F_ID]) then
		return false
	end
	if not db.otherFaction and row[QL.F_SIDE] ~= 0 and row[QL.F_SIDE] ~= 3 and row[QL.F_SIDE] ~= playerSide then
		return false
	end
	if not db.otherClass and row[QL.F_CLASS] ~= 0 and classBit and bit.band(row[QL.F_CLASS], classBit) == 0 then
		return false
	end
	local above = tonumber(db.levelAbove) or 0
	if above > 0 then
		local level = QL.Plain(UnitLevel("player")) or 60
		if row[QL.F_LEVEL] > level + above then
			return false
		end
	end
	return not QL.Closed(row)
end

