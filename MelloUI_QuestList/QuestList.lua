-- The account record (0.19.9, the Completed view: docs/plans/completed-quests.md):
-- which of your characters have done a quest or have it in their log, for the
-- quest tooltips (QL.RecordLines: your OTHER characters -- this one's own state
-- is the tooltip's). Account-wide, in MelloUIQuestRecord (SavedVariables):
-- { chars = { ["Name-Realm"] = { name, realm, class, level, seen,
-- done = { [questID] = true }, log = { [questID] = true } } } }. A character is
-- written as it logs out (PLAYER_LOGOUT: the game's own done set and its quest
-- log as they stand then), so nothing runs at login or per event. /mello alts
-- lists the characters; /mello alts forget <name> lets one go (a deleted
-- character stays until then).
--------------------------------------------------------------------------------
local Record = { me = nil, name = nil, realm = nil, order = nil, names = {} }   -- names: one line's (one table, wiped)
QL.Record = Record
local RECORD_NAMES = 6   -- names on one line, then "and N more"

function Record.Store()
	local s = rawget(_G, "MelloUIQuestRecord")
	if type(s) ~= "table" then
		s = {}
		_G.MelloUIQuestRecord = s
	end
	if type(s.chars) ~= "table" then
		s.chars = {}
	end
	return s
end

-- this character's key ("Name-Realm"), or nil while its name cannot be read
function Record.Me()
	if Record.me then
		return Record.me
	end
	local name = QL.Plain(UnitName("player"))
	local ok, realm = pcall(GetRealmName)
	realm = ok and QL.Plain(realm)
	if type(name) ~= "string" or name == "" or type(realm) ~= "string" then
		return nil
	end
	Record.me, Record.name, Record.realm = name .. "-" .. realm, name, realm
	return Record.me
end

-- This character as it logs out: the game's done set (kept as it was when the
-- game cannot hand it), and the quests in its log (the log's walk shows the
-- quests under open headers only: one met before stays while the game still
-- has it in the log)
function Record.Write()
	local key = Record.Me()
	if not key then
		return
	end
	local chars = Record.Store().chars
	local c = chars[key]
	if type(c) ~= "table" then
		c = {}
		chars[key] = c
	end
	local _, class = UnitClass("player")
	c.name, c.realm, c.class = Record.name, Record.realm, QL.Plain(class)
	c.level, c.seen = QL.Plain(UnitLevel("player")), time()
	local ok, ids = pcall(C_QuestLog.GetAllCompletedQuestIDs)
	if ok and type(ids) == "table" then
		local done = {}
		for _, id in ipairs(ids) do
			id = QL.Plain(id)
			if type(id) == "number" then
				done[id] = true
			end
		end
		c.done = done
	elseif type(c.done) ~= "table" then
		c.done = {}
	end
	local log, old = {}, type(c.log) == "table" and c.log or {}
	local okN, n = pcall(C_QuestLog.GetNumQuestLogEntries)
	n = okN and QL.Plain(n)
	for i = 1, type(n) == "number" and n or 0 do
		local okI, id = pcall(C_QuestLog.GetQuestIDForLogIndex, i)
		id = okI and QL.Plain(id)
		if type(id) == "number" and id > 0 then
			log[id] = true
		end
	end
	for id in pairs(old) do
		if not log[id] then
			local okQ, on = pcall(C_QuestLog.IsOnQuest, id)
			if okQ and QL.Plain(on) == true then
				log[id] = true
			end
		end
	end
	c.log = log
end

-- the other characters, by key (made once a session: their record does not
-- change while this one plays; a forget makes it again)
local function RecordOthers()
	local order = Record.order
	if order then
		return order
	end
	local me = Record.Me()
	order = {}
	for key, c in pairs(Record.Store().chars) do
		if key ~= me and type(c) == "table" then
			order[#order + 1] = key
		end
	end
	table.sort(order)
	if me then
		Record.order = order
	end
	return order
end

-- a character's name as a line shows it: its realm only when it is not yours
local function RecordName(key, c)
	local name = type(c.name) == "string" and c.name or key
	if type(c.realm) == "string" and c.realm ~= Record.realm then
		return name .. "-" .. c.realm
	end
	return name
end

-- the other characters with the quest in one of their sets ("done" or "log"),
-- as one line's list, or nil
local function RecordList(questID, set)
	local names, chars = Record.names, Record.Store().chars
	wipe(names)
	for _, key in ipairs(RecordOthers()) do
		local c = chars[key]
		if type(c) == "table" and type(c[set]) == "table" and c[set][questID] then
			names[#names + 1] = RecordName(key, c)
		end
	end
	local n = #names
	if n == 0 then
		return nil
	end
	if n > RECORD_NAMES then
		for i = n, RECORD_NAMES + 1, -1 do
			names[i] = nil
		end
		return table.concat(names, ", ") .. string.format(" and %d more", n - RECORD_NAMES)
	end
	return table.concat(names, ", ")
end

-- A quest's lines for your other characters (Your Other Characters On Quests,
-- the Quest List's Tooltips): who has done it, who has it in their log.
-- Nothing until a character has been written (the record's first logout).
function QL.RecordLines(tip, questID, indent)
	if not M.db.tipCharacters or type(rawget(_G, "MelloUIQuestRecord")) ~= "table" then
		return
	end
	local done = RecordList(questID, "done")
	if done then
		QL.TipLine(tip, (indent or "") .. "Done by " .. done, "text", true)
	end
	local log = RecordList(questID, "log")
	if log then
		QL.TipLine(tip, (indent or "") .. "In the quest log of " .. log, "text", true)
	end
end

