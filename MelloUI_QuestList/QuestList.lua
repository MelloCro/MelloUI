--------------------------------------------------------------------------------
-- World positions
--
-- Vanilla data gives world coordinates. The client turns them into a
-- continent-map position; the continent map's hit test says which zone (and
-- city) is there, and the zone's rectangle on the continent gives the position
-- on the zone map. Build-time zone guesses are wrong at zone edges and on maps
-- Forever changed (Stormwind with its harbour), so this is done here.
--------------------------------------------------------------------------------

function QL.VectorXY(pos)
	if type(pos) ~= "table" then
		return nil, nil
	end
	local x, y = QL.Plain(pos.x), QL.Plain(pos.y)
	if (x == nil or y == nil) and type(pos.GetXY) == "function" then
		local ok, gx, gy = pcall(pos.GetXY, pos)
		if ok then
			x, y = QL.Plain(gx), QL.Plain(gy)
		end
	end
	return x, y
end

-- Is `mapID` the map `uiMapID` or one of its parents (city inside a zone)?
local function IsOnOrUnder(uiMapID, mapID)
	local id = uiMapID
	for _ = 1, 4 do
		if id == mapID then
			return true
		end
		local ok, info = pcall(C_Map.GetMapInfo, id)
		id = ok and type(info) == "table" and QL.Plain(info.parentMapID) or nil
		if not id or id == 0 then
			return false
		end
	end
	return false
end

local rectCache = {}   -- [contMapID][mapID] = { minX, maxX, minY, maxY } or false
local WHOLE_MAP = { 0, 1, 0, 1 }   -- a map's rectangle on itself

-- Rectangle of a map on its continent map, cached. Keyed by the numbers
-- (no string made per look-up: every placed pin asks for it). A map on
-- itself is the whole map, not asked (a zone that is its own top map:
-- Zephras Isle, 0.14.0).
local function RectOn(mapID, contMapID)
	if mapID == contMapID then
		return WHOLE_MAP
	end
	local onCont = rectCache[contMapID]
	if not onCont then
		onCont = {}
		rectCache[contMapID] = onCont
	end
	local r = onCont[mapID]
	if r == nil then
		local ok, minX, maxX, minY, maxY = pcall(C_Map.GetMapRectOnMap, mapID, contMapID)
		minX, maxX, minY, maxY = QL.Plain(minX), QL.Plain(maxX), QL.Plain(minY), QL.Plain(maxY)
		r = (ok and minX and maxX and minY and maxY and maxX > minX and maxY > minY) and { minX, maxX, minY, maxY } or false
		onCont[mapID] = r
	end
	return r or nil
end

local function InRect(r, cx, cy)
	local x, y = (cx - r[1]) / (r[2] - r[1]), (cy - r[3]) / (r[4] - r[3])
	if x >= 0 and x <= 1 and y >= 0 and y <= 1 then
		return x, y
	end
	return nil
end

-- Is the map a zone (not a continent, the world or an instance)? Cached:
-- asked for each quest placed on a map with no continent above it.
local ZONE_TYPE = type(Enum) == "table" and type(Enum.UIMapType) == "table" and Enum.UIMapType.Zone
ZONE_TYPE = type(ZONE_TYPE) == "number" and ZONE_TYPE or 3
local zoneMaps = {}   -- [mapID] = true / false

local function IsZoneMap(mapID)
	local is = zoneMaps[mapID]
	if is == nil then
		local ok, info = pcall(C_Map.GetMapInfo, mapID)
		is = ok and type(info) == "table" and QL.Plain(info.mapType) == ZONE_TYPE or false
		zoneMaps[mapID] = is
	end
	return is
end

-- A world point as mapID, cx, cy, contMapID: the deepest map that holds it
-- (city before zone), its position on the continent map and that map; or
-- nil. QL.ProjectOnMap gives its position on a map (its own or another).
function QL.ResolveWorld(cont, wx, wy)
	if not (C_Map.GetMapPosFromWorldPos and CreateVector2D and C_Map.GetMapInfoAtPosition and C_Map.GetMapRectOnMap) then
		return nil
	end
	local ok, contMapID, pos = pcall(C_Map.GetMapPosFromWorldPos, cont, CreateVector2D(wx, wy))
	contMapID = ok and QL.Plain(contMapID) or nil
	local cx, cy = QL.VectorXY(pos)
	if not (contMapID and cx and cy) then
		return nil
	end
	local okZ, zinfo = pcall(C_Map.GetMapInfoAtPosition, contMapID, cx, cy)
	local zone = okZ and type(zinfo) == "table" and QL.Plain(zinfo.mapID) or nil
	local x, y
	if not zone or zone == contMapID then
		-- the top map itself: on a continent a gap between zones (placed
		-- nowhere); a zone with no continent above it is its own top map
		-- (Zephras Isle, 2521 right under the world map: the Zephras Isle
		-- fix, 0.14.0), placed on itself
		if not IsZoneMap(contMapID) then
			return nil
		end
		zone, x, y = contMapID, cx, cy
	else
		local r = RectOn(zone, contMapID)
		if r then
			x, y = InRect(r, cx, cy)
		end
		if not x then
			return nil
		end
	end
	-- One level deeper: a city inside the zone.
	local okC, cinfo = pcall(C_Map.GetMapInfoAtPosition, zone, x, y)
	local child = okC and type(cinfo) == "table" and QL.Plain(cinfo.mapID) or nil
	if child and child ~= zone then
		local r2 = RectOn(child, contMapID)
		if r2 and InRect(r2, cx, cy) then
			zone = child
		end
	end
	return zone, cx, cy, contMapID
end

-- Position on the map shown (`onMapID`) of a point ResolveWorld placed on
-- `mapID`: on its own map, a parent or a child, or nil when it is elsewhere.
-- On its own map that is the position ResolveWorld found it at: the same
-- rectangle (cached) and the same continent position.
function QL.ProjectOnMap(onMapID, mapID, cx, cy, contMapID)
	if not mapID then
		return nil
	end
	if mapID ~= onMapID and not (IsOnOrUnder(mapID, onMapID) or IsOnOrUnder(onMapID, mapID)) then
		return nil
	end
	local r = RectOn(onMapID, contMapID)
	if not r then
		return nil
	end
	return InRect(r, cx, cy)
end

-- Giver kinds: 1 NPC, 2 object, and an item that begins the quest: 3 dropped
-- by creatures, 4 picked up from an object; items sit at their densest spot.
QL.KIND_DROP, QL.KIND_PICKUP = 3, 4

function QL.IsItemStart(row)
	local kind = row[QL.F_KIND]
	return kind == QL.KIND_DROP or kind == QL.KIND_PICKUP
end

-- The dungeon or raid a quest's item or object is found in, when it is found
-- only inside one (no spot on the world map), or nil.
function QL.InstanceStart(row)
	if (row[QL.F_GIVER] or "") == "" or not (QL.IsItemStart(row) or row[QL.F_KIND] == 2) then
		return nil
	end
	if row[QL.F_X] ~= 0 or row[QL.F_Y] ~= 0 or (row[QL.F_CONT] or -1) >= 0 then
		return nil
	end
	local zone = row[QL.F_GIVERZONE]
	return zone ~= 0 and QL.Data().dungeons[zone] and zone or nil
end

