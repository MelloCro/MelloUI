local mapIDByName = nil

local function MapIDForZoneName(name)
	if not mapIDByName then
		mapIDByName = {}
		local ok, root = pcall(C_Map.GetFallbackWorldMapID)
		root = ok and QL.Plain(root) or 947
		local okC, children = pcall(C_Map.GetMapChildrenInfo, root, nil, true)
		if okC and type(children) == "table" then
			for _, info in ipairs(children) do
				local n = QL.Plain(info.name)
				local id = QL.Plain(info.mapID)
				if n and id and not mapIDByName[n:lower()] then
					mapIDByName[n:lower()] = id
				end
			end
		end
	end
	return mapIDByName[name:lower()]
end

function QL.ZoneNameForMap(mapID)
	if not mapID then
		return nil
	end
	local ok, info = pcall(C_Map.GetMapInfo, mapID)
	if ok and info then
