	for _, fn in ipairs(readyChecks) do
		local ok, ready = pcall(fn, questID)
		if ok and not IsSecret(ready) and ready ~= nil then
			return ready == true
		end
	end
	return false
end

-- What the game asks before it offers a quest (0.19.3; user, 2026-10-05: "the
-- quest list is showing me quests on the map that i can pick up, but when i
-- go there there are no quests"). The data's `needs` (build_quest_list.py:
-- the server's own checks from classic-db; a quest of Forever's own: the
-- quest before it in Wowhead's series), read in two ways:
--   QL.Closed  never offered to this character, now or later: a quest for
--              other races, one above its last level, a breadcrumb whose
--              quest is taken or done, one of a group of which only one can
--              be done once another is taken or done, one below a standing
--              the character is past. Out of the lists, the counts and the
--              map, like another class's quest (QL.Eligible)
--   QL.Unmet   not yet: a quest to do first (or to have in the log), a
--              profession's skill, a standing with a faction, or its giver
--              did not offer it when last asked (Offers, below). Listed,
--              never as one to pick up now, and not on the map
-- (A quest taken or done is the player's own: never closed, never unmet.)
local NO_NEEDS = {}
local function Needs()
	local data = QL.Data()
	return type(data) == "table" and data.needs or NO_NEEDS
end

local function TakenOrDone(questID)
	return QL.IsCompleted(questID) or QL.IsOnQuest(questID)
end

-- [questID] = its group of the data's `exclusive`, made on first use
local exclusiveOf = nil
local function ExclusiveOf(questID)
	if not exclusiveOf then
		exclusiveOf = {}
		for _, members in ipairs(Needs().exclusive or NO_NEEDS) do
			for _, id in ipairs(members) do
				exclusiveOf[id] = members
			end
		end
	end
	return exclusiveOf[questID]
end

-- The character's standing with a faction (the reputation bar's value: 0 is
-- Neutral, 3000 Friendly ...); 0 for one not met yet, nil when it cannot be
-- read (never holding a quest back then)
local function Standing(factionID)
	local ok, value
	if C_Reputation and C_Reputation.GetFactionDataByID then
		local info
		ok, info = pcall(C_Reputation.GetFactionDataByID, factionID)
		if ok and info == nil then
			return 0
		end
		value = ok and type(info) == "table" and QL.Plain(info.currentStanding)
	elseif GetFactionInfoByID then
		local name
		ok, name, _, _, _, _, value = pcall(GetFactionInfoByID, factionID)
		if ok and not name then
			return 0
		end
		value = ok and QL.Plain(value)
	end
	return type(value) == "number" and value or nil
end

-- A profession's skill (with its bonuses, as the server counts it); 0 when not
-- learned, nil when it cannot be read
local function Skill(skillLineID)
	if not (C_SkillInfo and C_SkillInfo.GetSkillLineInfoByID) then
		return nil
	end
	local ok, info = pcall(C_SkillInfo.GetSkillLineInfoByID, skillLineID)
	if not ok then
		return nil
	end
	local rank = type(info) == "table" and QL.Plain(info.rank)
	if type(rank) ~= "number" then
		return info == nil and 0 or nil
	end
	return rank + (QL.Plain(info.tempPoints) or 0) + (QL.Plain(info.modifier) or 0)
end

function QL.Closed(row)
	local id = row[QL.F_ID]
	local needs = Needs()
	local mask = needs.races and needs.races[id]
	if mask and raceBit and bit.band(mask, raceBit) == 0 then
		return true
	end
	local maxLevel = needs.maxLevel and needs.maxLevel[id]
	local target = needs.breadcrumbs and needs.breadcrumbs[id]
	local group = needs.exclusive and ExclusiveOf(id)
	local rep = needs.reps and needs.reps[id]
	local below = rep and rep[3] ~= 0
	-- (0.19.5; user, 2026-10-06: "only the ones i can pick up") the next
	-- quest of its chain taken or done (cmangos' Player::SatisfyQuestNextChain)
	local nextChain = needs.nextChain and needs.nextChain[id]
	if not (maxLevel or target or group or below or nextChain) or TakenOrDone(id) then
		return false
	end
	if nextChain and TakenOrDone(nextChain) then
		return true
	end
	if maxLevel and (QL.Plain(UnitLevel("player")) or 0) > maxLevel then
		return true
	end
	if target and TakenOrDone(target) then
		return true
	end
	if group then
		for _, other in ipairs(group) do
			if other ~= id and TakenOrDone(other) then
				return true
			end
		end
	end
	if below then
		local standing = Standing(rep[3])
		if standing and standing >= rep[4] then
			return true
		end
	end
	return false
end

-- One of `after`'s choices met: a quest done (a negative id: in the log), or
-- every quest of a list
local function AfterMet(choice)
	if type(choice) == "table" then
		for _, id in ipairs(choice) do
			if not AfterMet(id) then
				return false
			end
		end
		return true
	end
	if choice < 0 then
		return QL.IsOnQuest(-choice)
	end
	return QL.IsCompleted(choice)
end

-- The quest to name for a choice not met: itself, or a list's first not done
local function AfterName(choice)
	if type(choice) == "table" then
		for _, id in ipairs(choice) do
			if not AfterMet(id) then
				return math.abs(id)
			end
		end
		return math.abs(choice[1])
	end
	return math.abs(choice)
end

-- (0.19.5) a quest's condition: the data's `cond`, the server's own from
-- classic-db's conditions table (build_quest_list.py condition_tree). True,
-- false, or nil when it cannot be told from here (a place, an instance
-- script, the war effort's supplies, an aura that reads secret): nil never
-- holds a quest back. `depth` bounds a condition that asks whether another
-- quest can be picked up (leaf 19), whose own needs may ask again.
-- Leaves: {8, quest, rev} rewarded, {9, quest, rev} taken, {19, quest}
-- available, {23, item, count, rev} items with the bank (rev: fewer than),
-- {1, spell, rev} the player's aura; {0} cannot tell.
local function ItemCount(itemID)
	local f = C_Item and C_Item.GetItemCount or GetItemCount
	if type(f) ~= "function" then
		return nil
	end
	local ok, n = pcall(f, itemID, true)
	n = ok and QL.Plain(n)
	return type(n) == "number" and n or nil
end

function QL.CondMet(t, depth)
	local kind = t[1]
	if kind == "and" or kind == "or" then
		local unknown = false
		for i = 2, #t do
			local v = QL.CondMet(t[i], depth)
			if v == (kind == "or") then
				return v
			elseif v == nil then
				unknown = true
			end
		end
		if unknown then
			return nil
		end
		return kind == "and"
	elseif kind == "not" then
		local v = QL.CondMet(t[2], depth)
		if v == nil then
			return nil
		end
		return not v
	elseif kind == 8 or kind == 9 then
		local v = (kind == 8 and QL.IsCompleted or QL.IsOnQuest)(t[2])
		return (t[3] == 1) ~= v
	elseif kind == 23 then
		local n = ItemCount(t[2])
		if not n then
			return nil
		end
		local have = n >= math.max(t[3] or 1, 1)
		return (t[4] == 1) ~= have
	elseif kind == 1 then
		if not (C_UnitAuras and C_UnitAuras.GetPlayerAuraBySpellID) then
			return nil
		end
		local ok, aura = pcall(C_UnitAuras.GetPlayerAuraBySpellID, t[2])
		if not ok or IsSecret(aura) then
			return nil
		end
		return (t[3] == 1) ~= (aura ~= nil)
	elseif kind == 19 then
		depth = (depth or 0) + 1
		local row = RowByID()[t[2]]
		if not row or depth > 3 then
			return nil
		end
		if TakenOrDone(t[2]) then
			return false
		end
		return QL.Eligible(row) and QL.Unmet(row, depth) == nil
	end
	return nil
end

-- The words for a condition not met: its first leaf that is false
local function CondWhy(t, depth)
	local kind = t[1]
	if kind == "and" or kind == "or" then
		for i = 2, #t do
			if QL.CondMet(t[i], depth) == false then
				return CondWhy(t[i], depth)
			end
		end
		return nil
	elseif kind == "not" then
		return "Not yet offered to you"
	end
	local rev = (kind == 23 and t[4] or t[3]) == 1
	if kind == 8 or kind == 9 or kind == 19 then
		local other = RowByID()[t[2]]
		local title = other and other[QL.F_TITLE] or "another quest"
		if kind == 8 then
			return (rev and "Only before you hand in %s" or "After %s"):format(title)
		elseif kind == 9 then
			return (rev and "Not while you have %s in your log" or "While you have %s in your log"):format(title)
		end
		return ("While %s can still be picked up"):format(title)
	elseif kind == 23 then
		local ok, name = pcall(C_Item.GetItemNameByID, t[2])
		name = ok and QL.Plain(name) or "an item"
		return (rev and "Only without %s in your bags" or "Needs %s"):format(name)
	elseif kind == 1 then
		return "Needs a special effect on you"
	end
	return nil
end

-- For a quest neither taken nor done (the callers have asked already): nil
-- when the game would offer it now (its level aside: the callers compare
-- that), else why not: "after", questID, inLog (the quest to do first, or to
-- have in the log) / "skill", skill line, skill / "rep", faction, standing /
-- "crumb", questID (a breadcrumb leading to it is in the log) / "cond", its
-- words (the server's condition) / "refused", npc id, giver's name (not
-- offered the last time it was asked)
function QL.Unmet(row, depth)
	local id = row[QL.F_ID]
	local needs = Needs()
	local after = needs.after and needs.after[id]
	if after then
		local list = type(after) == "table" and after or { after }
		local met = false
		for _, choice in ipairs(list) do
			if AfterMet(choice) then
				met = true
				break
			end
		end
		if not met then
			local first = list[1]
			return "after", AfterName(first), type(first) == "number" and first < 0
		end
	end
	local skill = needs.skills and needs.skills[id]
	if skill then
		local have = Skill(skill[1])
		if have and have < math.max(skill[2], 1) then
			return "skill", skill[1], skill[2]
		end
	end
	local rep = needs.reps and needs.reps[id]
	if rep and rep[1] ~= 0 then
		local standing = Standing(rep[1])
		if standing and standing < rep[2] then
			return "rep", rep[1], rep[2]
		end
	end
	-- (0.19.5) a breadcrumb leading to it in the log: the server offers the
	-- quest only once that one is handed in
	local crumbs = needs.crumbsTo and needs.crumbsTo[id]
	if crumbs then
		for _, crumb in ipairs(crumbs) do
			if QL.IsOnQuest(crumb) then
				return "crumb", crumb
			end
		end
	end
	-- (0.19.5) the server's condition, where the client can tell
	local cond = needs.cond and needs.cond[id]
	if cond and QL.CondMet(cond, depth) == false then
		return "cond", CondWhy(cond, depth) or "Not yet offered to you"
	end
	-- (and what the data cannot know: its giver did not offer it, Offers below)
	local npc = QL.RefusedBy(id)
	if npc then
		return "refused", npc, row[QL.F_GIVER]
	end
	return nil
end

