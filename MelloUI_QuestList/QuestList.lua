	return (kind == "Creature" or kind == "Vehicle") and tonumber(id) or nil
end

-- The quests the open window offers, into `into`; false when they cannot
-- all be read
local function Listed(event, into)
	if event == "GOSSIP_SHOW" then
		local ok, list = pcall(C_GossipInfo.GetAvailableQuests)
		if not ok or type(list) ~= "table" then
			return false
		end
		for _, info in ipairs(list) do
			local id = type(info) == "table" and QL.Plain(info.questID)
			if type(id) ~= "number" then
				return false
			end
			into[id] = true
		end
		return true
	end
	local okN, n = pcall(GetNumAvailableQuests)   -- QUEST_GREETING
	n = okN and QL.Plain(n)
	if type(n) ~= "number" then
		return false
	end
	for i = 1, n do
		local ok, _, _, _, _, id = pcall(GetAvailableQuestInfo, i)
		id = ok and QL.Plain(id)
		if type(id) ~= "number" then
			return false
		end
		into[id] = true
	end
	return true
end

-- [npc id] = the data's quests that NPC gives, made with the first window
local function GivenBy(npcID)
	local byNpc = Offers.byNpc
	if not byNpc then
		byNpc = {}
		for _, row in pairs(RowByID()) do
			local npc = row[QL.F_NPC]
			if npc and npc ~= 0 then
				byNpc[npc] = byNpc[npc] or {}
				table.insert(byNpc[npc], row)
			end
		end
		Offers.byNpc = byNpc
	end
	return byNpc[npcID]
end

-- A quest giver's gossip or greeting (GOSSIP_SHOW, QUEST_GREETING): what it
-- offers now. True when that changed what is known
function Offers.Window(event)
	local npc = WindowNpc()
	local rows = npc and GivenBy(npc)
	if not rows then
		return false
	end
	local seen = Offers.seen
	wipe(seen)
	if not Listed(event, seen) then
		return false
	end
	local refused = Offers.Store().refused
	local changed = false
	for _, row in ipairs(rows) do
		local id = row[QL.F_ID]
		local was = refused[id]
		if seen[id] or TakenOrDone(id) then
			refused[id] = nil
		else
			refused[id] = npc
		end
		changed = changed or refused[id] ~= was
	end
	return changed
end

-- A quest's details from its giver (QUEST_DETAIL): offered
function Offers.Detail()
	local ok, id = pcall(GetQuestID)
	id = ok and QL.Plain(id)
	local refused = Offers.Store().refused
	if type(id) == "number" and refused[id] then
		refused[id] = nil
		return true
	end
	return false
end

-- A quest turned in (QUEST_TURNED_IN): its turn-in NPC is asked again
function Offers.TurnedIn(questID)
	local row = type(questID) == "number" and RowByID()[questID]
	local ender = row and row[QL.F_ENDERNPC]
	if not ender or ender == 0 then
		return false
	end
	local refused = Offers.Store().refused
	local changed = false
	for id, npc in pairs(refused) do
		if npc == ender then
			refused[id] = nil
			changed = true
		end
	end
	return changed
end

-- A level up (PLAYER_LEVEL_UP) or a skill changed (SKILL_LINES_CHANGED, a
-- profession learned among them): asked again when either moved
function Offers.Changed()
	return Offers.store ~= nil and Offers.Recheck(Offers.store)
end

-- The quest log walk, one for the Quest List (the panel's sums and the
-- quest tooltips' index; 0.14.0). QL.LogCalls: the log read by C_QuestLog
-- (true), the older calls (false) or not at all (nil).
function QL.LogCalls()
	if C_QuestLog and C_QuestLog.GetNumQuestLogEntries and C_QuestLog.GetQuestIDForLogIndex then
		return true
	elseif _G.GetNumQuestLogEntries and _G.GetQuestLogTitle then
		return false
	end
	return nil
end

-- the log's lines (headers too) and quests, nil when it cannot be read
function QL.LogSize(modern)
	local ok, lines, quests
	if modern then
		ok, lines, quests = pcall(C_QuestLog.GetNumQuestLogEntries)
	elseif modern == false then
		ok, lines, quests = pcall(_G.GetNumQuestLogEntries)
	end
	if not ok then
		return nil
	end
	lines, quests = QL.Plain(lines), QL.Plain(quests)
	if type(lines) ~= "number" or type(quests) ~= "number" then
		return nil
	end
	return lines, quests
end

-- the quest id on a log line, nil for a header
function QL.LogQuestID(modern, i)
	local ok, id
	if modern then
		ok, id = pcall(C_QuestLog.GetQuestIDForLogIndex, i)
	else
		local _, isHeader
		ok, _, _, _, isHeader, _, _, _, id = pcall(_G.GetQuestLogTitle, i)
		if ok and QL.Plain(isHeader) then
			return nil
		end
	end
	id = ok and QL.Plain(id) or nil
	return (type(id) == "number" and id > 0) and id or nil
end

-- The quests in the log: their ids into `into` (emptied first: one table
-- kept and filled again), then true when that is every quest of the log
-- (false when a folded header hides some, or the log cannot be read)
function QL.LogQuestIDs(into)
	wipe(into)
	local modern = QL.LogCalls()
	local lines, quests = QL.LogSize(modern)
	for i = 1, lines or 0 do
		local id = QL.LogQuestID(modern, i)
		if id then
			into[#into + 1] = id
		end
	end
	return lines ~= nil and #into >= quests
end

-- Quest log colouring: grey trivial, green easy, yellow fair, orange hard, red very hard.
-- The level the game colours a quest by: for a quest in the log its own
-- difficulty level (C_QuestLog.GetInfo, which can sit under the level shown
-- -- user, 2026-09-23: a quest green in the quest log was yellow in the
-- list), else the level of the data
function QL.ColourLevel(row)
	local level = row[QL.F_LEVEL]
	if C_QuestLog and C_QuestLog.GetLogIndexForQuestID and C_QuestLog.GetInfo then
		local ok, index = pcall(C_QuestLog.GetLogIndexForQuestID, row[QL.F_ID])
		index = ok and QL.Plain(index) or nil
		if index then
			local okI, info = pcall(C_QuestLog.GetInfo, index)
			local d = okI and type(info) == "table" and (QL.Plain(info.difficultyLevel) or QL.Plain(info.level)) or nil
			if type(d) == "number" and d > 0 then
				level = d
			end
		end
	end
	return level
end

-- A quest grey for you, as the game colours it (DifficultyUtil.
-- GetRelativeDifficultyColor: more than 4 levels under yours and further
-- than your trivial range, UnitQuestTrivialLevelRange); where the client
-- has no range, QL.DifficultyColor's own steps. A quest of no known level
-- is never grey.
function QL.IsGrey(row)
	local level = row[QL.F_LEVEL]
	local mine = type(UnitEffectiveLevel) == "function" and QL.Plain(UnitEffectiveLevel("player")) or nil
	if type(mine) ~= "number" then
		mine = QL.Plain(UnitLevel("player"))
	end
	if type(level) ~= "number" or level <= 0 or type(mine) ~= "number" then
		return false
	end
	local below = mine - level
	if below <= 4 then
		return false
	end
	local range
	if type(UnitQuestTrivialLevelRange) == "function" then
		local ok, r = pcall(UnitQuestTrivialLevelRange, "player")
		range = ok and QL.Plain(r) or nil
	end
	if type(range) == "number" then
		return below > range
	end
	local trivial = mine >= 40 and 12 or mine >= 30 and 9 or mine >= 20 and 7 or mine >= 10 and 6 or 5
	return below >= trivial
end

-- (0.19.5, the user's Hide Grey Quests; Questie hides them by default) a
-- quest not taken yet that the map leaves out for being grey -- never one in
-- the log, never the tracked one
function QL.GreyHidden(row, state)
	return state == "available" and M.db.hideGrey == true and QL.trackedQuestID ~= row[QL.F_ID] and QL.IsGrey(row)
end

function QL.DifficultyColor(level)
	if level <= 0 then
		return 0.75, 0.61, 0
	end
	if GetQuestDifficultyColor then
		local ok, color = pcall(GetQuestDifficultyColor, level)
		if ok and type(color) == "table" and color.r then
			return color.r, color.g, color.b
		end
	end
	local mine = QL.Plain(UnitLevel("player")) or 60
	local diff = level - mine
	if diff >= 5 then return 1, 0.1, 0.1 end
	if diff >= 3 then return 1, 0.5, 0.25 end
	if diff >= -2 then return 1, 0.82, 0 end
	local trivial = 5
	if mine >= 40 then trivial = 12 elseif mine >= 30 then trivial = 9 elseif mine >= 20 then trivial = 7 elseif mine >= 10 then trivial = 6 end
	if diff > -trivial then return 0.25, 0.75, 0.25 end
	return 0.5, 0.5, 0.5
end

