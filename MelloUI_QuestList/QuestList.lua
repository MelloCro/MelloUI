local eventFrame = CreateFrame("Frame")
Perf.SetScript(eventFrame, "OnEvent", function(_, event, ...)
	if event == "PLAYER_ENTERING_WORLD" then
		-- Instance info and quest flags settle a moment after the load.
		C_Timer.After(2, function()
			if not QL.LearnEntrance() then
				C_Timer.After(6, QL.LearnEntrance)
			end
			DungeonSummary()
		end)
		if QL.pendingExit then
			C_Timer.After(1, QL.LearnEntranceOnExit)
		end
	elseif event == "UNIT_SPELLCAST_SUCCEEDED" then
		-- Hearthstone or Astral Recall out of the instance: the arrival point
		-- is not the door.
		local _, _, spellID = ...
		spellID = QL.Plain(spellID)
		if spellID == 8690 or spellID == 556 then
			QL.pendingExit = nil
		end
	elseif event == "PLAYER_LEAVING_WORLD" or event == "ZONE_CHANGED" or event == "ZONE_CHANGED_INDOORS" or event == "ZONE_CHANGED_NEW_AREA" then
		QL.RememberOutside()
	elseif event == "QUEST_LOG_UPDATE" then
		-- counted only: the quest tooltips make their index again on the
		-- next tooltip that needs it (QuestListTips.lua)
		QL.logChanges = QL.logChanges + 1
		-- (0.19.5) the objective marks follow the log's progress while the map
		-- shows (once after a burst: QuestListObjectives.lua)
		if QL.Objectives then
			QL.Objectives.LogChanged()
		end
	elseif event == "PLAYER_LOGOUT" then
		-- (0.19.9) this character into the account record (QL.Record)
		QL.Record.Write()
		return
	elseif event == "NEUTRAL_FACTION_SELECT_RESULT" or (event == "UNIT_FACTION" and QL.Plain(...) == "player") then
		QL.SideChanged()
	else
		-- what the givers offer (Offers): the pins follow what was learned
		local changed
		if event == "GOSSIP_SHOW" or event == "QUEST_GREETING" then
			changed = QL.Offers.Window(event)
		elseif event == "QUEST_DETAIL" then
			changed = QL.Offers.Detail()
		elseif event == "QUEST_TURNED_IN" then
			changed = QL.Offers.TurnedIn(QL.Plain(...))
		elseif event == "PLAYER_LEVEL_UP" or event == "SKILL_LINES_CHANGED" then
			changed = QL.Offers.Changed()
		end
		if changed then
			QL.RefreshPins()
		end
	end
	if WorldMapFrame and WorldMapFrame:IsShown() then
		QL.Panel:Schedule()
	end
end)

