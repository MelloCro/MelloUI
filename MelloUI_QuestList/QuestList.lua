end

local function CurrentMapID()
	local ok, id = pcall(WorldMapFrame.GetMapID, WorldMapFrame)
	local mapID = ok and QL.Plain(id) or nil
	if not mapID then
		local okP, pid = pcall(C_Map.GetBestMapForUnit, "player")
		mapID = okP and QL.Plain(pid) or nil
	end
	return mapID
end

function QL.CurrentAreaID()
	local mapID = CurrentMapID()
	local name = QL.ZoneNameForMap(mapID)
	if not name then
		return nil, nil
	end
	local areaID = QL.zoneByName[name:lower()]
	if not areaID then
		-- A continent or the world is shown: use the zone the player is in.
		local okP, pid = pcall(C_Map.GetBestMapForUnit, "player")
		local pname = QL.ZoneNameForMap(okP and QL.Plain(pid) or nil)
		if pname then
			areaID, name = QL.zoneByName[pname:lower()], pname
		end
	end
	return areaID, name
end

-- The continent a zone of the data is grouped under by the Continent filter:
-- the data's (0 Eastern Kingdoms, 1 Kalimdor, 2991 Zephras Isle), or for a
-- zone the data places on no continent (-1) the zone on its own, as
-- -areaID (the Zephras Isle fix, 0.14.0: such a zone showed "Unknown
-- continent" and an empty list). The data's table is written that way on
-- the first ask (its -1 zones, once), so its other reader -- the panel's
-- Continent filter, `zoneContinent[zone] == c` -- lists such a zone's
-- quests alone. nil for a zone the data does not know.
function QL.ContinentOfZone(areaID)
	local data = QL.Data()
	local map = type(data) == "table" and data.zoneContinent
	if type(map) ~= "table" then
		return nil
	end
	if QL.ownContinents ~= map then
		QL.ownContinents = map
		for id, c in pairs(map) do
			if c == -1 and type(id) == "number" then
				map[id] = -id
			end
		end
	end
	return areaID and map[areaID] or nil
end

-- Continent of the map shown (as QL.ContinentOfZone), walking up the map
-- tree: its id and name.
function QL.CurrentContinent()
	local mapID = CurrentMapID()
	for _ = 1, 6 do
		if not mapID then break end
		local ok, info = pcall(C_Map.GetMapInfo, mapID)
		if not ok or not info then break end
		local name = QL.Plain(info.name)
		if name then
			for c, cname in pairs(QL.Data().continentNames or {}) do
				if cname:lower() == name:lower() then
					return c, cname
				end
			end
		end
		mapID = QL.Plain(info.parentMapID)
		if not mapID or mapID == 0 then break end
	end
	local areaID, zoneName = QL.CurrentAreaID()
	local c = QL.ContinentOfZone(areaID)
	if c then
		-- (a zone on its own is named as the zone)
		local names = QL.Data().continentNames
		return c, names and names[c] or zoneName
	end
	return nil, nil
end

-- The quest's giver (or turn-in) as the waypoint. True when set; the second
-- answer (here and in QL.RouteToPoint) is true when Route took it and its
-- notice says so with a sound, so the caller plays no click sound of its own
function QL.SetWaypoint(row, atEnder)
	local mapID, x, y
	if atEnder then
		mapID, x, y = QL.EndPoint(row)
	end
	if not x then
		mapID, x, y = QL.GiverPoint(row)
	end
	-- An item found only inside a dungeon or raid: to its entrance.
	local instance = not x and not atEnder and QL.InstanceStart(row)
	if instance then
		mapID, x, y = QL.EntrancePoint(instance)
	end
	if not x then
		return false
	end
	if not mapID then
		local zoneName = QL.Data().zones[QL.ZoneOf(row)]
		mapID = zoneName and MapIDForZoneName(zoneName)
	end
	if not mapID or not C_Map.SetUserWaypoint or not UiMapPoint then
		return false
	end
	local okCan, can = pcall(C_Map.CanSetUserWaypointOnMap, mapID)
	if okCan and can == false then
		return false
	end
	-- Through the Route module when it is on: pin, route, label and notice in one.
	local R = MelloUI.Route
	if R and R.isEnabled and R.SetDestinationTo then
		local who = atEnder and (row[QL.F_ENDER] or "") ~= "" and row[QL.F_ENDER] or row[QL.F_GIVER]
		local icon = atEnder and "|A:QuestTurnin:16:16|a " or "|A:QuestNormal:16:16|a "
		local label = icon .. row[QL.F_TITLE] .. (who ~= "" and (" - " .. who) or "")
		local what = atEnder and "turn-in" or QL.IsItemStart(row) and "item" or "quest giver"
		local text = string.format("%sTracking %s %s for %s, {dist} away", icon, what, who ~= "" and who or "", row[QL.F_TITLE])
		if instance then
			local kind = QL.IsRaid(instance) and "raid" or "dungeon"
			icon = QL.IsRaid(instance) and "|A:Raid:16:16|a " or "|A:Dungeon:16:16|a "
			label = icon .. row[QL.F_TITLE] .. " - " .. QL.Data().dungeons[instance]
			text = string.format("%sTracking the %s entrance of %s for %s (%s is found inside), {dist} away", icon, kind,
				QL.Data().dungeons[instance], row[QL.F_TITLE], who)
		end
		if R:SetDestinationTo({ mapID = mapID, x = x, y = y }, label, true, text) then
			QL.trackedQuestID = row[QL.F_ID]
			return true, R.AnnounceSounds ~= nil and R:AnnounceSounds()
		end
	end
	local point = UiMapPoint.CreateFromCoordinates(mapID, x, y)
	local ok = pcall(C_Map.SetUserWaypoint, point)
	if ok and C_SuperTrack and C_SuperTrack.SetSuperTrackedUserWaypoint then
		pcall(C_SuperTrack.SetSuperTrackedUserWaypoint, true)
	end
	if ok then
		QL.trackedQuestID = row[QL.F_ID]
	end
	return ok
end

-- Route to a point on a map (entrance, dock, flight master): the Route
-- module when it is on, else a plain user waypoint.
function QL.RouteToPoint(mapID, x, y, label, notice)
	if not (mapID and x and y) then
		return false
	end
	local R = MelloUI.Route
	if R and R.isEnabled and R.SetDestinationTo then
		if R:SetDestinationTo({ mapID = mapID, x = x, y = y }, label, true, notice) then
			return true, R.AnnounceSounds ~= nil and R:AnnounceSounds()
		end
		return false
	end
	if not (C_Map.SetUserWaypoint and UiMapPoint) then
		return false
	end
	local okCan, can = pcall(C_Map.CanSetUserWaypointOnMap, mapID)
	if okCan and can == false then
		return false
	end
	local ok = pcall(C_Map.SetUserWaypoint, UiMapPoint.CreateFromCoordinates(mapID, x, y))
	if ok and C_SuperTrack and C_SuperTrack.SetSuperTrackedUserWaypoint then
		pcall(C_SuperTrack.SetSuperTrackedUserWaypoint, true)
	end
	return ok
end

function QL.ClearWaypoint()
	if C_Map.ClearUserWaypoint then
		pcall(C_Map.ClearUserWaypoint)
	end
	QL.trackedQuestID = nil
end

-- The pin can be removed from the map itself; forget the quest then.
function QL.SyncTracked()
	if QL.trackedQuestID and C_Map.HasUserWaypoint then
		local ok, has = pcall(C_Map.HasUserWaypoint)
		if ok and has == false then
			QL.trackedQuestID = nil
		end
	end
end

